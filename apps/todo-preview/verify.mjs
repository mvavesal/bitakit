import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { parseEnv } from 'node:util';
import { chromium } from '@playwright/test';

const url = 'http://127.0.0.1:3103';
const env = parseEnv(await readFile(new URL('.env.local', import.meta.url), 'utf8'));
const title = `Preview task ${Date.now()}`;
const edited = `Edited ${title}`;
const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  await page.goto(url + '/auth/sign-in');
  const email = page.getByRole('textbox', { name: 'Email', exact: true });
  const password = page.getByLabel('Password', { exact: true });
  await email.fill('alice@example.test');
  await email.press('Tab');
  await password.fill(env.TODO_PREVIEW_PASSWORD);
  const sessionRefresh = page.waitForResponse((response) => response.url().endsWith('/api/auth/get-session'));
  // The native client revalidates the session when a browser tab becomes visible.
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
  await sessionRefresh;
  await page.waitForLoadState('networkidle');
  assert.equal(await email.inputValue() === 'alice@example.test', true, 'Email must survive tab visibility refresh');
  assert.equal(await password.inputValue() === env.TODO_PREVIEW_PASSWORD, true, 'Password must survive tab visibility refresh');
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await page.getByRole('heading', { name: 'Todos', exact: true }).waitFor();
  console.log('Sign-in succeeded; email and password survived Tab and native visibility refresh.');
  await page.getByRole('button', { name: 'Switch organization', exact: true }).click();
  await page.getByRole('menuitem', { name: /Design Studio/ }).click();
  await page.getByRole('textbox', { name: 'New task', exact: true }).fill(title);
  await page.getByRole('main').getByRole('button', { name: 'Add task', exact: true }).click();
  let row = page.getByRole('listitem').filter({ hasText: title });
  await row.getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByRole('textbox', { name: 'Task title', exact: true }).fill(edited);
  await page.getByRole('main').getByRole('button', { name: 'Save', exact: true }).click();
  row = page.getByRole('listitem').filter({ hasText: edited });
  await row.getByRole('button', { name: 'Complete', exact: true }).click();
  await row.getByText('Completed', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Switch organization', exact: true }).click();
  await page.getByRole('menuitem', { name: /Alice private team/ }).click();
  await page.getByRole('button', { name: 'Switch organization', exact: true }).filter({ hasText: 'Alice private team' }).waitFor();
  await row.waitFor({ state: 'detached' });
  await page.getByRole('button', { name: 'Switch organization', exact: true }).click();
  await page.getByRole('menuitem', { name: /Design Studio/ }).click();
  await row.getByRole('button', { name: 'Delete', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  await row.waitFor({ state: 'detached' });
  console.log('Create, edit, complete, delete and organization switching passed.');
  await page.goto(url + '/settings/account');
  await page.getByRole('heading', { name: 'Account', exact: true, level: 1 }).waitFor();
  console.log('Native account settings loaded.');
  await page.goto(url + '/todos');
  const aliceButton = page.getByRole('button', { name: /Alice \(test\).*alice@example.test/ });
  await aliceButton.click();
  await page.getByRole('menuitem', { name: /^Switch account$/i }).click();
  await page.getByRole('menuitem', { name: /^Add account$/i }).click();
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('bob@example.test');
  await page.getByLabel('Password', { exact: true }).fill(env.TODO_PREVIEW_PASSWORD);
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  const bobButton = page.getByRole('button', { name: /Bob \(test\).*bob@example.test/ });
  await bobButton.waitFor();
  await page.getByRole('button', { name: 'Switch organization', exact: true }).click();
  assert.equal(await page.getByRole('menuitem', { name: /Alice private team/ }).count(), 0);
  await page.keyboard.press('Escape');
  await page.getByRole('menu').waitFor({ state: 'hidden' });
  await bobButton.click();
  await page.getByRole('menuitem', { name: /^Switch account$/i }).click();
  await page.getByRole('menuitem', { name: /Alice \(test\).*alice@example.test/ }).click();
  await aliceButton.waitFor();
  console.log('Native Add account and switch back passed; Bob cannot see Alice’s private organization.');
} finally {
  await browser.close();
}
