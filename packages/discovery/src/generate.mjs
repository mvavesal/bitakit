/** Removes the generated files of the previous layout (`.foundation/`, `foundation-env.d.ts`). */
async function cleanupLegacy(root) {
  await removeGenerated(path.join(root, 'foundation-env.d.ts'));
  const legacy = path.join(root, '.foundation');
  for (const name of ['plugins.ts', 'app.ts', 'styles.css'])
    await removeGenerated(path.join(legacy, name));
  await rm(path.join(legacy, 'messages.json'), { force: true });
  if ((await readdir(legacy).catch(() => null))?.length === 0) await rmdir(legacy).catch(() => {});
}
