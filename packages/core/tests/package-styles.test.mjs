import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, realpath, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { generateFoundation, describeFoundation } from '@bitakit/discovery';

async function fixture(run) {
  const root = await realpath(await mkdtemp(path.join(tmpdir(), 'bitakit-styles-')));
  const install = async (name, manifest) => {
    const directory = path.join(root, 'node_modules', name);
    await mkdir(directory, { recursive: true });
    const metadata = manifest.bitakit ?? manifest.foundation ?? {};
    const css = [metadata.styles ?? [], metadata.theme ?? []].flat();
    const exports = { './package.json': './package.json' };
    for (const file of css) {
      exports[file] = file;
      await writeFile(path.join(directory, file), '/* fixture */');
    }
    await writeFile(path.join(directory, 'package.json'), JSON.stringify({ name, exports, ...manifest }));
  };
  const imports = async () =>
    (await readFile(path.join(root, 'src/bitakit.gen.css'), 'utf8'))
      .split('\n')
      .filter((line) => line.startsWith('@import'));
  try {
    await run({ root, install, imports });
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}

test('installed package styles are generated in dependency order with themes last, including transitive packages', async () =>
  fixture(async ({ root, install, imports }) => {
    await install('@acme/shell', {
      dependencies: { '@acme/ui': '1.0.0', '@acme/prefs': '1.0.0' },
      bitakit: { styles: './styles.css' },
    });
    await install('@acme/ui', {
      bitakit: { styles: ['./styles.css', './extra.css'], theme: './theme.css' },
    });
    // Not a direct dependency of the app: activated through @acme/shell.
    await install('@acme/prefs', { foundation: { styles: './styles.css' } });
    await install('@acme/headless', { bitakit: {} });
    await install('@acme/ignored', { bitakit: { styles: './styles.css' } });
    await writeFile(
      path.join(root, 'package.json'),
      JSON.stringify({
        dependencies: { '@acme/shell': '1.0.0', '@acme/ui': '1.0.0', '@acme/headless': '1.0.0' },
        devDependencies: { '@acme/ignored': '1.0.0' },
      }),
    );
    await generateFoundation(root, { quiet: true });
    const expected = [
      '@import "@acme/ui/styles.css";',
      '@import "@acme/ui/extra.css";',
      '@import "@acme/prefs/styles.css";',
      '@import "@acme/shell/styles.css";',
      '@import "@acme/ui/theme.css";',
    ];
    assert.deepEqual(await imports(), expected);
    const css = await readFile(path.join(root, 'src/bitakit.gen.css'), 'utf8');
    assert.match(
      css,
      /^\/\* Generated by BitaKit\. Do not edit\. Styles of installed packages, theme last\. \*\/\n/,
    );
    const description = await describeFoundation(root);
    assert.deepEqual(
      description.styles,
      expected.map((line) => line.slice('@import "'.length, -'";'.length)),
    );
    assert.deepEqual(description.installedPackages, [
      '@acme/headless',
      '@acme/shell',
      '@acme/ui',
      '@acme/prefs',
    ]);
    assert.deepEqual(description.packages, [], 'style-only packages contribute no plugin');

    await writeFile(
      path.join(root, 'bitakit.config.ts'),
      `export default { packages: { '@acme/ui': false } };`,
    );
    await generateFoundation(root, { quiet: true });
    assert.deepEqual(
      await imports(),
      ['@import "@acme/prefs/styles.css";', '@import "@acme/shell/styles.css";'],
      'deselected packages contribute no styles',
    );
  }));

test('an app without styled packages still gets an importable stylesheet', async () =>
  fixture(async ({ root, imports }) => {
    await writeFile(path.join(root, 'package.json'), '{}');
    const result = await generateFoundation(root, { quiet: true });
    const css = await readFile(path.join(root, 'src/bitakit.gen.css'), 'utf8');
    assert.match(css, /Generated by BitaKit/);
    assert.deepEqual(await imports(), []);
    assert.equal(
      path.dirname(result.generated),
      path.join(root, 'src'),
      'the stylesheet sits next to the generated TypeScript file',
    );
    assert.deepEqual((await describeFoundation(root)).styles, []);
  }));

test('style exports must stay inside their package', async () =>
  fixture(async ({ root, install }) => {
    await install('@acme/bad', { bitakit: { theme: './themes/../../outside.css' } });
    await writeFile(
      path.join(root, 'package.json'),
      JSON.stringify({ dependencies: { '@acme/bad': '1.0.0' } }),
    );
    await assert.rejects(
      generateFoundation(root, { quiet: true }),
      /Invalid BitaKit export in package "@acme\/bad"/,
    );
  }));
