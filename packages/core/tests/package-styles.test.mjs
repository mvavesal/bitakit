import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { generateFoundation } from '../discovery/generate.mjs';

test('installed package styles are generated in dependency order with themes last', async () => {
  const root = await mkdtemp(path.join(tmpdir(), 'foundation-styles-'));
  try {
    const pkg = async (name, manifest) => {
      const directory = path.join(root, 'node_modules', name);
      await mkdir(directory, { recursive: true });
      await writeFile(
        path.join(directory, 'package.json'),
        JSON.stringify({ name, exports: { './package.json': './package.json' }, ...manifest }),
      );
    };
    await pkg('@acme/shell', {
      dependencies: { '@acme/ui': '1.0.0' },
      foundation: { styles: './styles.css' },
    });
    await pkg('@acme/ui', { foundation: { styles: './styles.css', theme: './theme.css' } });
    await pkg('@acme/headless', { foundation: {} });
    await pkg('@acme/ignored', { foundation: { styles: './styles.css' } });
    await writeFile(
      path.join(root, 'package.json'),
      JSON.stringify({
        dependencies: { '@acme/shell': '1.0.0', '@acme/ui': '1.0.0', '@acme/headless': '1.0.0' },
        devDependencies: { '@acme/ignored': '1.0.0' },
      }),
    );
    await generateFoundation(root);
    const css = await readFile(path.join(root, '.foundation/styles.css'), 'utf8');
    assert.deepEqual(
      css.split('\n').filter((line) => line.startsWith('@import')),
      [
        '@import "@acme/ui/styles.css";',
        '@import "@acme/shell/styles.css";',
        '@import "@acme/ui/theme.css";',
      ],
    );
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test('an app without styled packages still gets an importable stylesheet', async () => {
  const root = await mkdtemp(path.join(tmpdir(), 'foundation-styles-'));
  try {
    await writeFile(path.join(root, 'package.json'), '{}');
    await generateFoundation(root);
    const css = await readFile(path.join(root, '.foundation/styles.css'), 'utf8');
    assert.match(css, /Generated by BitaKit/);
    assert.doesNotMatch(css, /@import/);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});
