import { readFile, writeFile, mkdir, realpath, rm, readdir, rmdir } from 'node:fs/promises';
import path from 'node:path';
import { createJiti } from 'jiti';
import { files, discoverEntries, contributionKindSpecs } from './entries.mjs';
import { installedContributions } from './packages.mjs';
import { pluginManifests } from './modules.mjs';

const quote = JSON.stringify;
/** Single-quoted module specifiers, matching the style of hand-written imports. */
const specifier = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
export const generatedHeader = '// Generated by BitaKit. Do not edit.';
const idPattern = /^[a-z][a-z0-9-]*$/;

async function writeChanged(file, content) {
  if ((await readFile(file, 'utf8').catch(() => null)) !== content) await writeFile(file, content);
}
async function removeGenerated(file, marker = 'Generated by') {
  const content = await readFile(file, 'utf8').catch(() => null);
  if (content !== null && content.includes(marker)) await rm(file, { force: true });
}

/** `bitakit.config.ts`, or the older `foundation.config.ts`. Missing is the default; errors inside propagate. */
export async function loadDiscoveryConfig(
  root,
  jiti = createJiti(import.meta.url, { moduleCache: false, fsCache: false }),
) {
  for (const name of ['bitakit.config.ts', 'foundation.config.ts']) {
    const file = path.join(root, name);
    const exists = await readFile(file, 'utf8').then(
      () => true,
      (error) => {
        if (error.code === 'ENOENT') return false;
        throw error;
      },
    );
    if (!exists) continue;
    const config = await jiti.import(file, { default: true });
    return { config: config ?? {}, file, legacy: name === 'foundation.config.ts' };
  }
  return { config: {}, file: undefined, legacy: false };
}

/** The framework whose provider the generated file wires: Next, TanStack Start, or none. */
export function detectFramework(manifest = {}) {
  const dependencies = { ...manifest.dependencies, ...manifest.devDependencies };
  if (dependencies.next) return 'next';
  if (dependencies['@tanstack/react-start'] || dependencies['@tanstack/react-router'])
    return 'tanstack';
  return 'none';
}

/**
 * Writes `src/bitakit.gen.tsx` (configuration, provider and type declarations),
 * `src/bitakit.gen.css` (package styles) and `src/bitakit.gen.messages.json` (plugin locales).
 * Only static imports are generated; contribution modules are never executed here.
 */
export async function generateFoundation(root, { quiet = false } = {}) {
  root = await realpath(root);
  const jiti = createJiti(import.meta.url, { moduleCache: false, fsCache: false });
  const warnings = [];
  const { config, legacy: legacyConfig } = await loadDiscoveryConfig(root, jiti);
  if (legacyConfig)
    warnings.push(
      'foundation.config.ts is deprecated: rename it to bitakit.config.ts and use defineBitaKit (run "bitakit migrate").',
    );
  const appRoot = path.resolve(root, config.directory ?? './src');
  const pluginsDirectory = path.resolve(root, config.plugins?.directory ?? './src/plugins');
  const installed = await installedContributions(root, config.packages, jiti);
  const rootManifest = await readFile(path.join(root, 'package.json'), 'utf8').then(
    JSON.parse,
    () => ({}),
  );
  const framework = config.framework ?? detectFramework(rootManifest);
  const output = appRoot;
  await mkdir(output, { recursive: true });
  const relativeTo = (file) => path.relative(root, file).split(path.sep).join('/');

  const roots = pluginManifests(pluginsDirectory, await files(pluginsDirectory));
  const included = Object.entries(config.plugins?.include ?? {}).map(([id, folder]) => {
    if (!idPattern.test(id))
      throw new Error(
        `Invalid included plugin ID "${id}". Use lowercase letters, digits and hyphens.`,
      );
    return { manifestFile: path.join(path.resolve(root, folder), 'plugin.config.ts'), id };
  });
  const modules = [...roots.map((manifestFile) => ({ manifestFile })), ...included];
  const moduleRoots = new Set(modules.map((module) => path.dirname(module.manifestFile)));

  const imports = [];
  let serial = 0;
  const importFile = (file, namespace = false) => {
    const name = `${namespace ? 'module' : 'entry'}${serial++}`;
    let relative = path
      .relative(output, file)
      .replaceAll(path.sep, '/')
      .replace(/\.tsx?$/, '');
    if (!relative.startsWith('.')) relative = `./${relative}`;
    imports.push(
      namespace
        ? `import * as ${name} from ${specifier(relative)};`
        : `import ${name} from ${specifier(relative)};`,
    );
    return name;
  };
  const types = { services: [], actions: [], events: [], cancelable: [], configs: [] };
  const fileEntries = (entries) =>
    entries.map((entry) => {
      const imported = importFile(entry.file);
      const name = `file${serial++}`;
      imports.push(
        `const ${name} = discoveredFile(${imported}, ${quote(entry.path.join('.'))}, ${quote(relativeTo(entry.file))});`,
      );
      return name;
    });
  const emit = (kind, entries, moduleId) => {
    const names = fileEntries(entries);
    if (kind === 'actions')
      for (const name of names)
        types.actions.push(`DiscoveredActionEntry<typeof ${name}, ${quote(moduleId)}>`);
    if (kind === 'services')
      for (const name of names)
        types.services.push(`DiscoveredServiceEntry<typeof ${name}, ${quote(moduleId)}>`);
    if (kind === 'events')
      for (const name of names) {
        types.events.push(`DiscoveredEventsEntry<typeof ${name}, ${quote(moduleId)}>`);
        types.cancelable.push(`DiscoveredCancelableEntry<typeof ${name}, ${quote(moduleId)}>`);
      }
    if (kind === 'configs')
      types.configs.push(
        `${quote(moduleId)}: ${names.map((name) => `DiscoveredConfigEntry<typeof ${name}>`).join(' & ') || '{}'};`,
      );
    const fn = {
      actions: 'discoverActions',
      services: 'discoverServices',
      interceptors: 'discoverInterceptors',
      configs: 'discoverConfig',
      events: 'discoverEvents',
    }[kind];
    const extra = kind === 'actions' || kind === 'services' ? `, ${quote(moduleId)}` : '';
    return `${fn}([${names.join(', ')}]${extra})`;
  };
  /** UI entries import the module namespace so `layout`, `order` and `requires` exports travel along. */
  const emitUI = (kind, entries, moduleId, isApp) =>
    entries.map((entry) => {
      const name = importFile(entry.file, true);
      if (kind === 'pages') {
        const base = isApp ? '' : `/${moduleId}`;
        const pagePath = `${base}${entry.path.length ? `/${entry.path.join('/')}` : ''}` || '/';
        return `pluginPage(${name}, ${quote(pagePath)})`;
      }
      if (kind === 'slots') return `pluginSlot(${name}, ${quote(entry.path.join('.'))})`;
      return `pluginProvider(${name}, ${quote(isApp ? entry.path.join('.') : `${moduleId}.${entry.path.join('.')}`)})`;
    });

  const kinds = contributionKindSpecs([
    ...new Map(
      [...contributionKindSpecs(installed.kinds), ...contributionKindSpecs(config.kinds)].map(
        (kind) => [kind.name, kind],
      ),
    ).values(),
  ]);
  const normalizers = new Map();
  const kindTypes = new Map();
  const contributions = (entriesByKind, moduleId) => {
    const parts = [];
    kinds.forEach((kind, index) => {
      const entries = entriesByKind[index];
      if (!entries.length) return;
      if (!normalizers.has(kind.name)) {
        const alias = `normalize${index}`;
        imports.push(`import { ${kind.normalize} as ${alias} } from ${specifier(kind.from)};`);
        normalizers.set(kind.name, alias);
      }
      const names = fileEntries(entries);
      if (kind.types) {
        if (!kindTypes.has(kind.name)) {
          imports.push(
            `import type { ${kind.types.entry} as KindEntry${index} } from ${specifier(kind.from)};`,
          );
          kindTypes.set(kind.name, { kind, index, entries: [] });
        }
        kindTypes
          .get(kind.name)
          .entries.push(
            ...names.map((name) => `KindEntry${index}<typeof ${name}, ${quote(moduleId)}>`),
          );
      }
      parts.push(
        `${quote(kind.name)}: ${normalizers.get(kind.name)}([${names.join(', ')}], ${quote(moduleId)})`,
      );
    });
    return `{ ${parts.join(', ')} }`;
  };
  const collect = async (base, list, kind, options) => {
    const result = await discoverEntries(base, list, kind, { ...options, relativeTo: root });
    warnings.push(...result.warnings);
    return result.entries;
  };

  // The application module.
  const appManifestFile = path.join(appRoot, 'plugin.config.ts');
  const appManifest = await readFile(appManifestFile, 'utf8')
    .then(() => jiti.import(appManifestFile, { default: true }))
    .catch((error) => {
      if (error.code === 'ENOENT') return {};
      throw error;
    });
  const appId = appManifest.id ?? 'app';
  if (!idPattern.test(appId))
    throw new Error(`Invalid app module ID "${appId}". Use lowercase letters, digits and hyphens.`);
  const pluginIds = new Set([appId]);
  const enabledModuleIds = new Set([appId]);
  const appFiles = (await files(appRoot, moduleRoots)).filter(
    (file) => !/[\\/]bitakit\.gen\./.test(file),
  );
  const appEntries = async (kind) => {
    const selected = config[kind];
    if (selected === false) return [];
    if (selected?.directory) {
      const directory = path.resolve(root, selected.directory);
      return collect(appRoot, await files(directory, moduleRoots), kind, { directory });
    }
    // Apps keep ordinary React providers in src/providers; only ui/providers (or `enabled`) count.
    return collect(appRoot, appFiles, kind, {
      legacy: kind !== 'providers' || config.providers?.enabled !== undefined,
    });
  };
  const appContributions = contributions(
    await Promise.all(kinds.map((kind) => collect(appRoot, appFiles, kind))),
    appId,
  );
  const appPrefix = appManifest.id ?? '';
  const appActions = emit('actions', await appEntries('actions'), appPrefix);
  const appServices = emit('services', await appEntries('services'), appPrefix);
  const appEvents = emit(
    'events',
    appFiles
      .filter((file) => file === path.join(appRoot, 'events.ts'))
      .map((file) => ({ file, path: [], source: relativeTo(file) })),
    appId,
  );
  const appConfigExpression = emit('configs', await appEntries('configs'), appId);
  let interceptorEntries = await appEntries('interceptors');
  if (config.interceptors?.enabled !== undefined) {
    const enabled = config.interceptors.enabled;
    if (new Set(enabled).size !== enabled.length)
      throw new Error('An interceptor is listed twice in interceptors.enabled.');
    interceptorEntries = enabled.map((id) => {
      const entry = interceptorEntries.find((item) => item.path.join('.') === id);
      if (!entry)
        throw new Error(
          `interceptors.enabled names "${id}", but no interceptor file with that name exists.`,
        );
      return entry;
    });
  }
  const appInterceptors = emit('interceptors', interceptorEntries, appId);
  const appPages = emitUI('pages', await appEntries('pages'), appId, true);
  const appSlots = emitUI('slots', await appEntries('slots'), appId, true);
  // Providers under ui/providers are included; the legacy providers/ folder needs the enabled list.
  let providerEntries = await appEntries('providers');
  if (config.providers?.enabled !== undefined) {
    const enabled = config.providers.enabled;
    if (new Set(enabled).size !== enabled.length)
      throw new Error('A provider is listed twice in providers.enabled.');
    providerEntries = enabled.map((id) => {
      const entry = providerEntries.find((item) => item.path.join('.') === id);
      if (!entry)
        throw new Error(
          `providers.enabled names "${id}", but no provider file with that name exists.`,
        );
      return entry;
    });
  }
  const appProviders = emitUI('providers', providerEntries, appId, true);
  const appSetupFile = appFiles.find((file) => file === path.join(appRoot, 'setup.ts'));
  const appSetup = appSetupFile ? importFile(appSetupFile) : 'undefined';

  // Local plugins.
  const definitions = [];
  const allMessages = {};
  for (const { manifestFile, id } of modules) {
    const base = path.dirname(manifestFile);
    const overrides = await readFile(manifestFile, 'utf8')
      .then(() => jiti.import(manifestFile, { default: true }))
      .catch((error) => {
        if (error.code === 'ENOENT' && error.path === manifestFile) return {};
        throw error;
      });
    const manifest = { id: path.basename(base), ...overrides, ...(id ? { id } : {}) };
    if (!idPattern.test(manifest.id))
      throw new Error(
        `Invalid plugin ID "${manifest.id}" (${relativeTo(base)}). Use lowercase letters, digits and hyphens.`,
      );
    if (pluginIds.has(manifest.id))
      throw new Error(
        `Plugin ID "${manifest.id}" is used twice (${relativeTo(base)}). Rename the folder or set id in plugin.config.ts.`,
      );
    pluginIds.add(manifest.id);
    const enabled =
      config.plugins?.overrides?.[manifest.id]?.enabled ?? config.plugins?.autoEnable ?? true;
    const readPackage = (folder) =>
      readFile(path.join(folder, 'package.json'), 'utf8')
        .then(JSON.parse)
        .catch((error) => {
          if (error.code === 'ENOENT') return undefined;
          throw error;
        });
    const packageInfo =
      (await readPackage(base)) ?? (id ? await readPackage(path.dirname(base)) : undefined) ?? {};
    const metadata = {};
    for (const key of ['name', 'version', 'description', 'author', 'homepage', 'bugs', 'license']) {
      const value = manifest.metadata?.[key] ?? packageInfo[key];
      if (value !== undefined) metadata[key] = value;
    }
    const resolveEntry = async (name, fallback) => {
      const override = manifest.entries?.[name];
      if (override === false) return [];
      const target = path.resolve(base, override ?? fallback);
      const relative = path.relative(base, target);
      if (relative.startsWith('..') || path.isAbsolute(relative))
        throw new Error(
          `Entry "${name}" of plugin "${manifest.id}" points outside the plugin: ${target}`,
        );
      const actual = await realpath(target).catch((error) => {
        if (error.code === 'ENOENT') return null;
        throw error;
      });
      if (!actual) {
        if (override)
          throw new Error(`Plugin "${manifest.id}" names a missing entry for "${name}": ${target}`);
        return [];
      }
      if (actual !== target) throw new Error(`Symlink entry in plugin "${manifest.id}": ${target}`);
      return /\.tsx?$/.test(target) ? [target] : files(target);
    };
    const moduleFiles = await files(
      base,
      new Set([...moduleRoots].filter((item) => item !== base)),
    );
    const entriesFor = async (kind) => {
      const name = typeof kind === 'string' ? kind : kind.name;
      const override = manifest.entries?.[name];
      if (override === false) return [];
      if (override) {
        const paths = await resolveEntry(name, override);
        const target = path.resolve(base, override);
        return collect(
          base,
          paths,
          kind,
          /\.tsx?$/.test(target) ? { explicitFile: target } : { directory: target },
        );
      }
      return collect(base, moduleFiles, kind);
    };
    if (!enabled) continue;
    enabledModuleIds.add(manifest.id);
    const eventsFile = moduleFiles.find((file) => file === path.join(base, 'events.ts'));
    const setupFiles = await resolveEntry('setup', 'setup.ts');
    const actions = emit('actions', await entriesFor('actions'), manifest.id);
    const services = emit('services', await entriesFor('services'), manifest.id);
    const events = emit(
      'events',
      eventsFile ? [{ file: eventsFile, path: [], source: relativeTo(eventsFile) }] : [],
      manifest.id,
    );
    const pluginConfig = emit('configs', await entriesFor('configs'), manifest.id);
    const pluginInterceptors = emit('interceptors', await entriesFor('interceptors'), manifest.id);
    const pages = emitUI('pages', await entriesFor('pages'), manifest.id, false);
    const slots = emitUI('slots', await entriesFor('slots'), manifest.id, false);
    const providers = emitUI('providers', await entriesFor('providers'), manifest.id, false);
    const setup = setupFiles[0] ? importFile(setupFiles[0]) : 'undefined';
    const pluginContributions = contributions(
      await Promise.all(kinds.map((kind) => entriesFor(kind))),
      manifest.id,
    );
    definitions.push(
      `{ id: ${quote(manifest.id)}, metadata: ${quote(metadata)}, dependencies: ${quote(manifest.dependencies ?? [])}, events: ${events}, actions: ${actions}, services: ${services}, config: ${pluginConfig}, interceptors: ${pluginInterceptors}, ui: { pages: [${pages.join(', ')}], slots: [${slots.join(', ')}], providers: [${providers.join(', ')}] }, setup: ${setup}, contributions: ${pluginContributions} }`,
    );
    for (const file of await resolveEntry('locales', 'locales')) {
      if (!file.endsWith('.json')) continue;
      const locale = path.basename(file, '.json');
      const messages = JSON.parse(await readFile(file, 'utf8'));
      if (Object.keys(messages).some((key) => key !== manifest.id))
        throw new Error(
          `${relativeTo(file)}: locale keys must sit under the plugin namespace "${manifest.id}".`,
        );
      (allMessages[locale] ??= {})[manifest.id] = messages[manifest.id];
    }
  }

  // Installed packages.
  const configured = Object.keys(installed.configurations ?? {}).length > 0;
  const packageImports = installed.plugins.map(
    (entry, index) => `import packagePlugin${index} from ${specifier(entry)};`,
  );
  const packageFactories = installed.plugins.map((entry, index) => {
    const configPath = installed.configurations?.[entry];
    return `packagePlugin${index}(${configPath ? `options.get(${quote(configPath)}, {})` : ''})`;
  });
  const configOverrides = Object.fromEntries(
    Object.entries(config.configOverrides ?? {}).filter(
      ([id]) => !pluginIds.has(id) || enabledModuleIds.has(id),
    ),
  );
  const slotNames = [
    ...new Set([
      ...(installed.packages.includes('@bitakit/ui') ? ['app-bar.end'] : []),
      ...(config.slots ?? []),
    ]),
  ];
  const strict = config.strict !== false;
  const provider =
    framework === 'next' ? '@bitakit/next' : framework === 'tanstack' ? '@bitakit/tanstack' : null;
  const extension = provider ? 'tsx' : 'ts';
  const intersect = (list) => list.join(' & ') || '{}';
  const typeImports = [
    types.actions.length && 'type DiscoveredActionEntry',
    types.services.length && 'type DiscoveredServiceEntry',
    types.events.length && 'type DiscoveredEventsEntry',
    types.cancelable.length && 'type DiscoveredCancelableEntry',
    types.configs.some((entry) => entry.includes('DiscoveredConfigEntry')) &&
      'type DiscoveredConfigEntry',
    installed.plugins.length && 'type PublicServicesOf',
  ].filter(Boolean);
  const body = [...definitions, appPages.join(''), appSlots.join(''), appProviders.join('')].join(
    '\n',
  );
  const helpers = ['pluginPage', 'pluginSlot', 'pluginProvider'].filter((helper) =>
    body.includes(`${helper}(`),
  );
  const content = `${generatedHeader}
${provider ? "'use client';\n" : ''}import {
  discoveredFile,
  discoverActions,
  discoverServices,
  discoverInterceptors,
  discoverConfig,
  discoverEvents,
${helpers.map((helper) => `  ${helper},\n`).join('')}${configured ? '  ConfigService,\n' : ''}  type FoundationConfig,
${typeImports.map((item) => `  ${item},`).join('\n')}
} from '@bitakit/core';
${imports.join('\n')}
${packageImports.join('\n')}
${provider ? `import { FoundationProvider } from ${specifier(provider)};\nimport { useState, type ComponentProps } from 'react';\n` : ''}
type DiscoveredServices = ${intersect(types.services)};
type DiscoveredActions = ${intersect(types.actions)};
type DiscoveredEvents = ${intersect(types.events)};
type DiscoveredCancelable = ${intersect(types.cancelable)};
${installed.plugins.length ? `type InstalledPlugins = [${installed.plugins.map((_, index) => `ReturnType<typeof packagePlugin${index}>`).join(', ')}];\ntype InstalledServices = PublicServicesOf<InstalledPlugins>;` : 'type InstalledServices = {};'}
${[...kindTypes.values()].map(({ kind, index, entries }) => `type KindMap${index} = ${entries.join(' & ')};\ndeclare module ${specifier(kind.from)} { interface ${kind.types.map} extends KindMap${index} {} }`).join('\n')}
declare module '@bitakit/core' {
  interface ServiceMap extends DiscoveredServices, InstalledServices {}
  interface PublicServiceMap extends InstalledServices {}
  interface ActionMap extends DiscoveredActions {}
  interface EventMap extends DiscoveredEvents {}
  interface CancelableEventMap extends DiscoveredCancelable {}
  interface ConfigMap {
    ${types.configs.join('\n    ')}
  }
  interface SlotMap { ${slotNames.map((name) => `${quote(name)}: true;`).join(' ')} }
${strict ? '  interface ActionMapOptions { strict: true }\n' : ''}}

/** Everything discovery found, as one runtime configuration. Create it once per runtime. */
export function createBitaKitConfig() {
  const appConfig = ${appConfigExpression};
  const configOverrides: Record<string, Record<string, unknown>> = ${quote(configOverrides)};
${configured ? `  const options = new ConfigService([{ id: ${quote(appId)}, config: appConfig }], { [${quote(appId)}]: configOverrides[${quote(appId)}] ?? {} }).plugin(${quote(appId)});\n` : ''}  return {
    appId: ${quote(appId)},
    metadata: ${quote(appManifest.metadata ?? {})},
    dependencies: ${quote(appManifest.dependencies ?? [])},
    groups: ${quote(config.groups ?? [])},
    actionOverrides: ${quote((config.actions && config.actions.overrides) || {})},
    config: appConfig,
    configOverrides,
    events: ${appEvents},
    services: ${appServices},
    actions: ${appActions},
    interceptors: ${appInterceptors},
    ui: { pages: [${appPages.join(', ')}], slots: [${appSlots.join(', ')}], providers: [${appProviders.join(', ')}] },
    setup: ${appSetup},
    contributions: ${appContributions},
    plugins: [
      ${[...definitions, ...packageFactories].join(',\n      ')}
    ],
  } satisfies FoundationConfig;
}
export type BitaKitConfig = ReturnType<typeof createBitaKitConfig>;
/** @deprecated Use createBitaKitConfig. */
export const createFoundationConfig = createBitaKitConfig;
${
  provider
    ? `
/** Mounts the generated configuration. Place it once in the root layout. */
export function BitaKitProvider(props: Omit<ComponentProps<typeof FoundationProvider>, 'config'>) {
  const [config] = useState(createBitaKitConfig);
  return <FoundationProvider {...props} config={config} />;
}
`
    : ''
}`;
  const generated = path.join(output, `bitakit.gen.${extension}`);
  await writeChanged(generated, content);
  await removeGenerated(path.join(output, `bitakit.gen.${extension === 'tsx' ? 'ts' : 'tsx'}`));
  await writeChanged(
    path.join(output, 'bitakit.gen.css'),
    `/* ${generatedHeader.slice(3)} Styles of installed packages, theme last. */\n${(installed.styles ?? []).map((specifier) => `@import ${quote(specifier)};`).join('\n')}\n`,
  );
  const messagesFile = path.join(output, 'bitakit.gen.messages.json');
  if (Object.keys(allMessages).length)
    await writeChanged(messagesFile, JSON.stringify(allMessages, null, 2) + '\n');
  else await rm(messagesFile, { force: true });
  await cleanupLegacy(root);
  if (!quiet) for (const warning of warnings) console.warn(`[bitakit] ${warning}`);
  return {
    included: included.map((module) => path.dirname(module.manifestFile)),
    warnings,
    generated,
    framework,
  };
}

/** Removes the generated files of the previous layout (`.foundation/`, `foundation-env.d.ts`). */
async function cleanupLegacy(root) {
  await removeGenerated(path.join(root, 'foundation-env.d.ts'));
  const legacy = path.join(root, '.foundation');
  for (const name of ['plugins.ts', 'app.ts', 'styles.css'])
    await removeGenerated(path.join(legacy, name));
  await rm(path.join(legacy, 'messages.json'), { force: true });
  if ((await readdir(legacy).catch(() => null))?.length === 0) await rmdir(legacy).catch(() => {});
}
