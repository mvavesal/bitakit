/** Shared package composition; framework adapters supply their own dependencies and scripts. */
export async function configureProject(
  plan,
  { packages, dependencies = {}, devDependencies = {}, scripts = {} },
) {
  const file = path.join(plan.target, 'package.json');
  const project = JSON.parse(await readFile(file, 'utf8'));
  for (const name of ['core', 'ui', ...packages])
    project.dependencies[`@bitakit/${name}`] = bitakitRange;
  Object.assign(project.dependencies, dependencies);
  project.devDependencies = {
    ...project.devDependencies,
    '@bitakit/cli': bitakitRange,
    ...devDependencies,
  };
  Object.assign((project.scripts ??= {}), scripts);
  await writeProjectFile(plan.target, 'package.json', JSON.stringify(project, null, 2) + '\n');
  const ignored = await readFile(path.join(plan.target, '.gitignore'), 'utf8').catch((error) => {
    if (error.code !== 'ENOENT') throw error;
    return 'node_modules/\ndist/\n.env*\n';
  });
  await writeProjectFile(
    plan.target,
    '.gitignore',
    `${ignored.trimEnd()}\n\n# Generated by BitaKit discovery\nsrc/bitakit.gen.*\n`,
  );
}

/** Tailwind first, then the generated import of every installed package's styles. */
export function projectStyles(fromDirectory) {
  return `@import 'tailwindcss';
/* Styles of the installed BitaKit packages, generated by discovery. Add your own CSS below. */
@import '${fromDirectory}/bitakit.gen.css';
`;
}

