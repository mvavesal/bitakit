import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { stylePrelude } from '@bitakit/discovery';
import { agentRules as sharedAgentRules, bitakitIdentity, gitignoreBlock } from '@bitakit/cli';
import { runScript } from './package-manager.mjs';

const manifest = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));
/**
 * Generated projects depend on the release line of this generator (`^0.2.0` for 0.2.x), not on
 * its exact version: only changed packages get a patch release, so other @bitakit packages may
 * be behind the generator within one line. npm still installs the newest patch of each.
 */
export const bitakitRange = releaseLineRange(manifest.version);

/** `^0.<minor>.0` before 1.0, `^<major>.0.0` after: the versions a caret range treats as one line. */
export function releaseLineRange(version) {
  const [major, minor] = version.split('.');
  return major === '0' ? `^0.${minor}.0` : `^${major}.0.0`;
}

/** Write a generated project file; only called after the empty destination was created. */
export async function writeProjectFile(root, file, content) {
  const destination = path.join(root, file);
  await mkdir(path.dirname(destination), { recursive: true });
  await writeFile(destination, content);
}
export async function writeProjectFiles(root, files) {
  for (const [file, content] of Object.entries(files)) await writeProjectFile(root, file, content);
}

/**
 * The oldest release of a package that the generated files work with, when that is newer than
 * the start of the line. Without it a resolver that skips fresh releases (pnpm's
 * minimumReleaseAge) or an older lockfile installs a version missing an API the files use.
 * Raise an entry when a template starts using a newer API; drop entries at a new release line.
 */
export const minimumVersions = {
  // Discovery binds provenance through Core; keep the generated API and runtime together.
  core: '0.2.8',
  discovery: '0.2.5',
  // 0.2.5: not-found.tsx renders `<AppShell layout="error">` and error pages Shell's screens.
  // 0.2.6: Shell declares HeroUI's peers, which Yarn does not install by itself.
  shell: '0.2.6',
};

/** The dependency range for a generated project: the release line, from its minimum if any. */
export function packageRange(name) {
  return minimumVersions[name] ? `^${minimumVersions[name]}` : bitakitRange;
}

export const optionalPackages = {
  preferences: 'app-preferences',
  shell: 'shell',
  'quick-search': 'quick-search',
};

/** Shared package composition; framework adapters supply their own dependencies and scripts. */
export async function configureProject(
  plan,
  { packages, dependencies = {}, devDependencies = {}, scripts = {} },
) {
  const file = path.join(plan.target, 'package.json');
  const project = JSON.parse(await readFile(file, 'utf8'));
  for (const name of ['core', 'ui', ...packages])
    project.dependencies[`@bitakit/${name}`] = packageRange(name);
  Object.assign(project.dependencies, dependencies);
  project.devDependencies = {
    ...project.devDependencies,
    '@bitakit/cli': bitakitRange,
    '@bitakit/discovery': packageRange('discovery'),
    ...devDependencies,
  };
  Object.assign((project.scripts ??= {}), scripts);
  await writeProjectFile(plan.target, 'package.json', JSON.stringify(project, null, 2) + '\n');
  const ignored = await readFile(path.join(plan.target, '.gitignore'), 'utf8').catch((error) => {
    if (error.code !== 'ENOENT') throw error;
    return 'node_modules/\ndist/\n.env*\n';
  });
  await writeProjectFile(plan.target, '.gitignore', `${ignored.trimEnd()}\n\n${gitignoreBlock}`);
}

/** Tailwind first, then the generated import of every installed package's styles. */
export function projectStyles(fromDirectory) {
  return `${stylePrelude}
@import 'tailwindcss';
/* Styles of the installed BitaKit packages, generated by discovery. Add your own CSS below. */
@import '${fromDirectory}/bitakit.gen.css';
`;
}

