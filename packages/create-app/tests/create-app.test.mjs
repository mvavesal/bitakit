import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm, symlink, access } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { execa } from 'execa';
import { fileURLToPath } from 'node:url';
import { planProject, createApp, useLocalPackages } from '../src/create-app.mjs';
import { bitakitRange } from '../src/project-files.mjs';

async function workspace(t) {
  const root = await mkdtemp(path.join(os.tmpdir(), 'foundation-create-test-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  return root;
}
const read = (target, file) => readFile(path.join(target, file), 'utf8');

// The real official scaffold/install/build path is verified against packed packages separately.
async function scaffoldOnly(command, args) {
  assert.equal(command, process.execPath);
  assert.ok(args.includes('--skip-install'));
  assert.ok(args.includes('--disable-git'));
  const target = args[1];
  await mkdir(path.join(target, 'src/app'), { recursive: true });
  await writeFile(
    path.join(target, 'package.json'),
    JSON.stringify({ dependencies: { next: '16.3.5' }, devDependencies: {}, scripts: {} }),
  );
  await writeFile(path.join(target, 'src/app/page.tsx'), 'export default function Page() {}');
  await writeFile(path.join(target, '.gitignore'), 'node_modules/\n');
  await writeFile(path.join(target, 'AGENTS.md'), '<!-- next rules -->\n');
}

test('rejects existing directories and symlinks without touching user files', async (t) => {
  const root = await workspace(t);
  const existing = path.join(root, 'existing');
  await mkdir(existing);
  await writeFile(path.join(existing, 'keep.txt'), 'user content');
  await symlink(existing, path.join(root, 'linked'));
  await assert.rejects(planProject(existing), /already exists/);
  await assert.rejects(planProject(path.join(root, 'linked')), /already exists/);
  assert.equal(await readFile(path.join(existing, 'keep.txt'), 'utf8'), 'user content');
});

test('defaults to the full app frame and resolves prerequisites before writing', async (t) => {
  const root = await workspace(t);
  const target = path.join(root, 'app');
  assert.deepEqual((await planProject(target)).features, ['preferences', 'shell', 'quick-search']);
  assert.deepEqual((await planProject(target, { features: [] })).features, []);
  await assert.rejects(planProject(target, { framework: 'unsupported' }), /Unsupported framework/);
  await assert.rejects(planProject(target, { features: ['unknown'] }), /Unknown feature/);
  await assert.rejects(access(target));
});

test('a bare app has one provider, one CSS import and a catch-all for plugin pages', async (t) => {
  const root = await workspace(t);
  const plan = await planProject(path.join(root, 'app'), { features: [], install: false });
  await createApp(plan, { run: scaffoldOnly });
  const manifest = JSON.parse(await read(plan.target, 'package.json'));
  assert.equal(manifest.dependencies['@bitakit/shell'], undefined);
  assert.equal(manifest.dependencies['@bitakit/next'], bitakitRange);
  assert.equal(manifest.dependencies['@bitakit/core'], bitakitRange);
  assert.equal(manifest.devDependencies['@bitakit/cli'], bitakitRange);
  assert.equal(manifest.dependencies['tw-animate-css'], undefined);
  assert.equal((await read(plan.target, 'src/app/layout.tsx')).match(/<FoundationProvider>/g).length, 1);
  assert.equal(
    await read(plan.target, 'src/app/globals.css'),
    "@import 'tailwindcss';\n/* Styles of the installed BitaKit packages, generated by discovery. Add your own CSS below. */\n@import '../../.foundation/styles.css';\n",
  );
  assert.match(await read(plan.target, 'src/app/[...path]/page.tsx'), /<PluginPage/);
  await access(path.join(plan.target, 'src/app/page.tsx'));
  await assert.rejects(access(path.join(plan.target, 'src/app/settings')));
  await assert.rejects(access(path.join(plan.target, 'src/plugins')));
  const rules = await read(plan.target, 'AGENTS.md');
  assert.match(rules, /^<!-- next rules -->/);
  assert.match(rules, /npx bitakit add plugin <name>/);
  assert.match(await read(plan.target, '.gitignore'), /\.foundation\/\nfoundation-env\.d\.ts/);
});

test('the shell app renders plugin pages and settings with one route file each', async (t) => {
  const root = await workspace(t);
  const plan = await planProject(path.join(root, 'app'), { install: false, sample: true });
  await createApp(plan, { run: scaffoldOnly });
  const manifest = JSON.parse(await read(plan.target, 'package.json'));
  assert.equal(manifest.dependencies['@bitakit/app-preferences'], bitakitRange);
  assert.equal(manifest.dependencies['@bitakit/quick-search'], bitakitRange);
  assert.doesNotMatch(await read(plan.target, 'src/app/layout.tsx'), /NuqsAdapter/);
  assert.match(await read(plan.target, 'src/app/(app)/layout.tsx'), /<AppShell>/);
  assert.match(await read(plan.target, 'src/app/(app)/[...path]/page.tsx'), /NotFoundPage/);
  assert.match(await read(plan.target, 'src/app/settings/[[...section]]/page.tsx'), /<SettingsRoute \/>/);
  await access(path.join(plan.target, 'src/configs/shell.ts'));
  await assert.rejects(access(path.join(plan.target, 'src/app/page.tsx')));
  for (const file of ['services/todos.ts', 'actions/add.ts', 'actions/open.ts', 'pages/todos.tsx'])
    await access(path.join(plan.target, 'src/plugins/todos', file));
  assert.match(await read(plan.target, 'README.md'), /working sample/);
});

test('CLI dry-run does not create files and unsupported framework exits with an error', async (t) => {
  const root = await workspace(t);
  const cli = fileURLToPath(new URL('../src/cli.mjs', import.meta.url));
  const target = path.join(root, 'app');
  const result = await execa(process.execPath, [cli, target, '--features', 'quick-search', '--sample', '--dry-run', '--yes']);
  assert.match(result.stdout, /preferences, shell, quick-search/);
  assert.match(result.stdout, /Todos plugin/);
  await assert.rejects(access(target));
  const rejected = await execa(process.execPath, [cli, target, '--framework', 'unsupported', '--yes'], { reject: false });
  assert.notEqual(rejected.exitCode, 0);
  await assert.rejects(access(target));
});

test('installation failures propagate and leave generated files available for inspection', async (t) => {
  const root = await workspace(t);
  const plan = await planProject(path.join(root, 'app'));
  await assert.rejects(
    createApp(plan, {
      run: async (command, args) => {
        if (command === 'npm') throw new Error('Registry unavailable');
        await scaffoldOnly(command, args);
      },
    }),
    /Registry unavailable/,
  );
  await access(path.join(plan.target, 'package.json'));
});

test('TanStack apps get the same frame through native file routes', async (t) => {
  const root = await workspace(t);
  const plan = await planProject(path.join(root, 'start'), { framework: 'tanstack', install: false });
  await createApp(plan, {
    run: async (_command, args) => {
      assert.ok(args.includes('--blank'));
      assert.ok(args.includes('--no-install'));
      assert.ok(args.includes('--no-git'));
      await mkdir(path.join(plan.target, 'src/routes'), { recursive: true });
      await writeFile(path.join(plan.target, 'package.json'), JSON.stringify({ dependencies: {}, scripts: {} }));
      await writeFile(path.join(plan.target, 'src/routes/index.tsx'), 'export {};');
    },
  });
  const manifest = JSON.parse(await read(plan.target, 'package.json'));
  assert.equal(manifest.dependencies['@bitakit/tanstack'], bitakitRange);
  assert.equal(manifest.dependencies['@bitakit/next'], undefined);
  assert.match(await read(plan.target, 'src/routes/__root.tsx'), /FoundationProvider/);
  assert.match(await read(plan.target, 'src/routes/_app.tsx'), /<AppShell>/);
  assert.match(await read(plan.target, 'src/routes/_app.$.tsx'), /<PluginPage/);
  assert.match(await read(plan.target, 'src/routes/settings.$.tsx'), /SettingsRoute/);
  assert.match(await read(plan.target, 'src/styles.css'), /@import '\.\.\/\.foundation\/styles\.css';/);
  await assert.rejects(access(path.join(plan.target, 'src/routes/index.tsx')));
  assert.equal(await read(plan.target, 'CLAUDE.md'), '@AGENTS.md\n');
});

test('local tarballs replace every @bitakit dependency, including dev tools', async (t) => {
  const root = await workspace(t);
  const tarballs = path.join(root, 'tarballs');
  await mkdir(tarballs);
  for (const name of ['core', 'ui', 'next', 'cli']) await writeFile(path.join(tarballs, `bitakit-${name}-0.2.0.tgz`), '');
  const target = path.join(root, 'app');
  await mkdir(target);
  await writeFile(
    path.join(target, 'package.json'),
    JSON.stringify({
      dependencies: { '@bitakit/core': '^0.2.0', '@bitakit/ui': '^0.2.0', '@bitakit/next': '^0.2.0' },
      devDependencies: { '@bitakit/cli': '^0.2.0' },
    }),
  );
  await useLocalPackages(target, tarballs);
  const manifest = JSON.parse(await read(target, 'package.json'));
  assert.equal(manifest.devDependencies['@bitakit/cli'], `file:${path.join(tarballs, 'bitakit-cli-0.2.0.tgz')}`);
  assert.equal(manifest.overrides['@bitakit/core'], `file:${path.join(tarballs, 'bitakit-core-0.2.0.tgz')}`);
});
