import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import ts from 'typescript';
import {
  agentRulesBegin,
  claudeFileFor,
  projectAgentRules,
  refreshAgentRules,
} from './agent-rules.mjs';
import { cliVersion, writeAppDevelopmentSkills } from './agent-skill.mjs';
import { exists, findProject } from './project.mjs';
import { appRoutes, catchAllRoute, rootLayouts, shellGroup } from './routes.mjs';

// Wiring text shared with `create-bitakit-app`, which imports it from this package.
export const nextConfigImport = "import { withBitaKit } from '@bitakit/next/config';";
export const nextConfigFile = `${nextConfigImport}\n\nexport default withBitaKit({});\n`;
export const viteConfigImport = "import { bitakit } from '@bitakit/tanstack/config';";
export const bitakitConfigFile =
  "import { defineBitaKit } from '@bitakit/discovery';\n\nexport default defineBitaKit({});\n";
export const gitignoreBlock = '# Generated by BitaKit discovery\nsrc/bitakit.gen.*\n';

const parse = (source, fileName) =>
  ts.createSourceFile(fileName, source, ts.ScriptTarget.Latest, true);
/** Applies `{ start, end?, insert }` edits from the end of the file, so earlier offsets stay valid. */
const apply = (source, edits) =>
  [...edits]
    .sort((a, b) => b.start - a.start)
    .reduce(
      (result, { start, end = start, insert }) =>
        result.slice(0, start) + insert + result.slice(end),
      source,
    );
/** Adds an import after the last import (or directive) of a file. */
function importEdit(file, line) {
  const last = file.statements
    .filter(
      (item) =>
        ts.isImportDeclaration(item) ||
        (ts.isExpressionStatement(item) && ts.isStringLiteral(item.expression)),
    )
    .at(-1);
  return last ? { start: last.end, insert: `\n${line}` } : { start: 0, insert: `${line}\n` };
}

/**
 * `export default config;` becomes `export default withBitaKit(config);` with its import, keeping
 * everything the framework scaffold configured (for example Tailwind's Turbopack loader rule).
 * Returns undefined for shapes it cannot edit safely.
 */
export function wrapNextConfig(source, fileName) {
  const file = parse(source, fileName);
  const exported = file.statements.find(
    (item) => ts.isExportAssignment(item) && !item.isExportEquals,
  );
  if (!exported) return undefined;
  const { expression } = exported;
  return apply(source, [
    {
      start: expression.getStart(file),
      end: expression.end,
      insert: `withBitaKit(${expression.getText(file)})`,
    },
    importEdit(file, nextConfigImport),
  ]);
}
/** Puts `bitakit()` first in the Vite `plugins` array. */
function addVitePlugin(source, fileName) {
  const file = parse(source, fileName);
  let array;
  const visit = (node) => {
    if (array) return;
    if (
      ts.isPropertyAssignment(node) &&
      node.name.getText(file) === 'plugins' &&
      ts.isArrayLiteralExpression(node.initializer)
    )
      array = node.initializer;
    else ts.forEachChild(node, visit);
  };
  visit(file);
  if (!array) return undefined;
  const [first] = array.elements;
  const start = first ? first.getStart(file) : array.getStart(file) + 1;
  const lead = first ? source.slice(array.getStart(file) + 1, start) : '';
  return apply(source, [
    { start, insert: first ? `bitakit(),${lead.includes('\n') ? lead : ' '}` : 'bitakit()' },
    importEdit(file, viteConfigImport),
  ]);
}
/** Wraps `{children}` (or, in TanStack, `<Outlet />`) of the root layout in `<BitaKitProvider>`. */
function wrapLayout(source, fileName, specifier, framework) {
  const file = parse(source, fileName);
  const find = (matches) => {
    let found;
    const visit = (node) => {
      if (found) return;
      if (matches(node)) found = node;
      else ts.forEachChild(node, visit);
    };
    visit(file);
    return found;
  };
  const target =
    find(
      (node) =>
        ts.isJsxExpression(node) &&
        node.expression &&
        ts.isIdentifier(node.expression) &&
        node.expression.text === 'children',
    ) ??
    (framework === 'tanstack'
      ? find((node) => ts.isJsxSelfClosingElement(node) && node.tagName.getText(file) === 'Outlet')
      : undefined);
  if (!target) return undefined;
  return apply(source, [
    {
      start: target.getStart(file),
      end: target.end,
      insert: `<BitaKitProvider>${target.getText(file)}</BitaKitProvider>`,
    },
    importEdit(file, `import { BitaKitProvider } from '${specifier}';`),
  ]);
}

/**
 * Wires an existing Next.js or TanStack Start app: `bitakit.config.ts`, the config wrapper or
 * Vite plugin, the provider in the root layout, the catch-all route for plugin pages, the
 * `.gitignore` entry and the agent rules in `AGENTS.md` (the same block create-app writes), which
 * `CLAUDE.md` imports.
 * Files that already carry the wiring are never touched. With `updateAgentFiles`, the BitaKit
 * block of `AGENTS.md` is replaced with the current rules and unedited skill copies are updated
 * (see `writeAppDevelopmentSkills`); edited copies are kept.
 * Returns `written` (absolute paths; `created` is false for an edited file; `note` says what an
 * update changed), `skipped` with the reason for each, and the BitaKit packages the app still has
 * to install.
 */
export async function initProject({ cwd, updateAgentFiles = false } = {}) {
  const project = await findProject(cwd);
  if (project.kind !== 'app') throw new Error('Run "bitakit init" inside an app.');
  if (!project.framework)
    throw new Error(
      '"bitakit init" wires Next.js and TanStack Start apps. Add next or @tanstack/react-start first.',
    );
  const written = [];
  const skipped = [];
  const at = (file) => path.join(project.root, file);
  const read = (file) => readFile(file, 'utf8').catch(() => undefined);
  const first = async (files) => {
    for (const file of files) if (await exists(file)) return file;
  };
  const put = async (file, content, created = false, note) => {
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, content);
    written.push(note ? { file, created, note } : { file, created });
  };
  const skip = (file, reason) => skipped.push({ file, reason });

  const configFile = at('bitakit.config.ts');
  if (await exists(configFile)) skip(configFile, 'already exists');
  else if (await exists(at('foundation.config.ts')))
    skip(configFile, 'foundation.config.ts is the 0.1 name; run "npx bitakit migrate"');
  else await put(configFile, bitakitConfigFile, true);

  if (project.framework === 'next') {
    const file =
      (await first(['next.config.ts', 'next.config.mjs', 'next.config.js'].map(at))) ??
      at('next.config.ts');
    const source = await read(file);
    if (source === undefined) await put(file, nextConfigFile, true);
    else if (/withBitaKit/.test(source))
      skip(file, 'already wraps the configuration with withBitaKit');
    else if (/withFoundation/.test(source))
      skip(file, 'uses the removed withFoundation; run "npx bitakit migrate"');
    else {
      const wrapped = wrapNextConfig(source, file);
      if (wrapped) await put(file, wrapped);
      else
        skip(
          file,
          `no "export default" to wrap; use withBitaKit(<config>) from @bitakit/next/config`,
        );
    }
  } else {
    const file = at('vite.config.ts');
    const source = await read(file);
    if (source === undefined)
      skip(file, 'not found; add bitakit() from @bitakit/tanstack/config to the Vite plugins');
    else if (/\bbitakit\(/.test(source)) skip(file, 'already runs the BitaKit plugin');
    else if (/\bfoundation\(/.test(source))
      skip(file, 'uses the removed foundation() plugin; run "npx bitakit migrate"');
    else {
      const updated = addVitePlugin(source, file);
      if (updated) await put(file, updated);
      else skip(file, 'no plugins array; add bitakit() from @bitakit/tanstack/config to it');
    }
  }

  const layouts = rootLayouts(project).map(at);
  const layout = await first(layouts);
  if (!layout)
    skip(layouts[0], 'not found; mount <BitaKitProvider> from the generated file around your app');
  else {
    const source = (await read(layout)) ?? '';
    if (/bitakit\.gen|BitaKitProvider|BitaKitRuntimeProvider/.test(source))
      skip(layout, 'already mounts the BitaKit provider');
    else {
      const relative = path
        .relative(path.dirname(layout), path.join(project.appDirectory, 'bitakit.gen'))
        .split(path.sep)
        .join('/');
      const specifier = relative.startsWith('.') ? relative : `./${relative}`;
      const updated = wrapLayout(source, layout, specifier, project.framework);
      if (updated) await put(layout, updated);
      else skip(layout, 'no {children} to wrap; mount <BitaKitProvider> around your app');
    }
  }

  const group = await shellGroup(project);
  const shell =
    project.framework === 'next' ? Boolean(group) : await exists(at('src/routes/_app.tsx'));
  const route = catchAllRoute(project, { shell, group });
  const caught = (await appRoutes(project)).find(
    (item) => item.catchAll && item.pattern.test('/bitakit-plugin-page'),
  );
  if (caught) skip(at(route.file), `${caught.file} already catches every path`);
  else if (await exists(at(route.file))) skip(at(route.file), 'already exists');
  else await put(at(route.file), route.content, true);

  const ignored = await read(at('.gitignore'));
  if (ignored?.includes('bitakit.gen'))
    skip(at('.gitignore'), 'already ignores the generated files');
  else
    await put(
      at('.gitignore'),
      ignored === undefined ? gitignoreBlock : `${ignored.trimEnd()}\n\n${gitignoreBlock}`,
      ignored === undefined,
    );

  const dependencies = { ...project.manifest.dependencies, ...project.manifest.devDependencies };
  const agentsFile = at('AGENTS.md');
  const agents = await read(agentsFile);
  const rules = await projectAgentRules(project);
  const refreshed = refreshAgentRules(agents, rules);
  if (!agents?.includes(agentRulesBegin))
    await put(
      agentsFile,
      agents === undefined ? rules : `${agents.trimEnd()}\n\n${rules}`,
      agents === undefined,
    );
  else if (refreshed === agents)
    skip(
      agentsFile,
      updateAgentFiles ? 'the BitaKit rules are up to date' : 'already has the BitaKit rules',
    );
  else if (refreshed === undefined)
    skip(agentsFile, 'the BitaKit block has no end marker; restore it by hand');
  else if (!updateAgentFiles)
    skip(agentsFile, 'already has the BitaKit rules; --update-agent-files refreshes them');
  else await put(agentsFile, refreshed, false, 'refreshed the BitaKit rules');
  // Claude Code loads CLAUDE.md, so it imports the rules; an existing file only gets the import line.
  const claudeFile = at('CLAUDE.md');
  const claude = await read(claudeFile);
  const claudeNext = claudeFileFor(claude);
  if (claudeNext === claude) skip(claudeFile, 'already imports AGENTS.md');
  else await put(claudeFile, claudeNext, claude === undefined);

  for (const skill of await writeAppDevelopmentSkills(project.root, {
    update: updateAgentFiles,
  })) {
    if (skill.change === 'installed') written.push({ file: skill.file, created: true });
    else if (skill.change)
      written.push({
        file: skill.file,
        created: false,
        note:
          skill.change === 'updated'
            ? `updated from ${skill.version}`
            : `up to date; stamped with ${cliVersion}`,
      });
    else skip(skill.file, skillReason(skill, updateAgentFiles));
  }

  const install = [
    '@bitakit/core',
    '@bitakit/discovery',
    '@bitakit/ui',
    project.framework === 'next' ? '@bitakit/next' : '@bitakit/tanstack',
  ].filter((name) => !dependencies[name]);
  // The rules and the skill tell agents to run `npx bitakit ...`, which needs the local CLI; a
  // one-off `npx @bitakit/cli init` does not install it.
  const installDev = ['@bitakit/cli'].filter((name) => !dependencies[name]);
  return { project, written, skipped, install, installDev };
}

/** Why `init` left an existing skill copy alone. */
function skillReason(skill, update) {
  if (!update)
    return skill.state === 'outdated'
      ? `already exists; preserved; --update-agent-files updates it from ${skill.version} to ${cliVersion}`
      : 'already exists; preserved';
  if (skill.state === 'current') return 'up to date';
  if (skill.state === 'newer')
    return `from @bitakit/cli ${skill.version}, newer than this CLI; kept`;
  return `edited locally; kept. Delete its folder and run again to get ${cliVersion}`;
}
