import { execFileSync } from 'node:child_process';
import { cp, mkdir, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { describeModule } from '@bitakit/core/discovery';
import { findProject } from './project.mjs';

const quote = JSON.stringify;
const header = '// Generated by BitaKit. Do not edit.\n';

/**
 * Builds a plugin package from the same folders apps use. It generates the plugin's own types
 * (`.foundation/plugin.d.ts`), compiles `src` with the package's TypeScript config and writes
 * `dist/foundation.js`, the entry apps discover. `check` stops after a type check.
 */
export async function buildPlugin({ cwd, check = false } = {}) {
  const project = await findProject(cwd);
  if (project.kind !== 'plugin')
    throw new Error('Run "bitakit build" inside a plugin package (a package.json with foundation.plugin).');
  const { root, pluginId: id, moduleRoot, manifest } = project;
  const module = await describeModule(moduleRoot);
  await mkdir(path.join(root, '.foundation'), { recursive: true });
  await writeFile(
    path.join(root, '.foundation/plugin.d.ts'),
    declarations(id, module, (file) => `../${path.relative(root, file).split(path.sep).join('/').replace(/\.tsx?$/, '')}`),
  );
  const tsc = createRequire(path.join(root, 'package.json')).resolve('typescript/bin/tsc');
  const compile = (args) => {
    try {
      execFileSync(process.execPath, [tsc, '-p', 'tsconfig.json', ...args], { cwd: root, stdio: 'pipe' });
    } catch (error) {
      throw new Error(`TypeScript found problems:\n${String(error.stdout || error.message).trim()}`);
    }
  };
  if (check) {
    compile(['--noEmit']);
    return { id, module, checked: true };
  }
  const dist = path.join(root, 'dist');
  await rm(dist, { recursive: true, force: true });
  compile([]);
  const local = (file) => `./${path.relative(module.directory, file).split(path.sep).join('/').replace(/\.tsx?$/, '.js')}`;
  await writeFile(path.join(dist, 'foundation.js'), entry(id, module, manifest, local));
  await writeFile(
    path.join(dist, 'foundation.d.ts'),
    `${declarations(id, module, (file) => local(file))}import type { Plugin } from '@bitakit/core';
/** Creates the "${id}" plugin. Apps discover it through package.json foundation.plugin. */
declare const plugin: () => Plugin & { readonly id: ${quote(id)} };
export default plugin;
`,
  );
  if (module.locales.length) {
    await mkdir(path.join(dist, 'locales'), { recursive: true });
    for (const file of module.locales) await cp(file, path.join(dist, 'locales', path.basename(file)));
  }
  return { id, module, dist };
}

/** Typed services, actions and config for TypeScript, through @bitakit/core augmentation. */
function declarations(id, module, specifier) {
  const lines = [];
  const files = (entries, kind) =>
    entries.map((entry, index) => {
      const name = `${kind}${index}`;
      lines.push(`import type ${name}Entry from ${quote(specifier(entry.file))};`);
      lines.push(`type ${name} = DiscoveredFile<typeof ${name}Entry, ${quote(entry.path)}>;`);
      return name;
    });
  const services = files(module.services, 'Service');
  const actions = files(module.actions, 'Action');
  const configs = files(module.configs, 'Config');
  const intersect = (items, map) => items.map(map).join(' & ') || '{}';
  return `${header}import type { DiscoveredFile, DiscoveredServiceEntry, DiscoveredPublicServiceEntry, DiscoveredActionEntry, DiscoveredConfigEntry } from '@bitakit/core';
${lines.join('\n')}
type PluginServices = ${intersect(services, (name) => `DiscoveredServiceEntry<${name}, ${quote(id)}>`)};
type PluginPublicServices = ${intersect(services, (name) => `DiscoveredPublicServiceEntry<${name}>`)};
type PluginActions = ${intersect(actions, (name) => `DiscoveredActionEntry<${name}, ${quote(id)}, true>`)};
declare module '@bitakit/core' {
  interface ServiceMap extends PluginServices, PluginPublicServices {}
  interface PublicServiceMap extends PluginPublicServices {}
  interface ActionMap extends PluginActions {}
  interface ConfigMap { ${quote(id)}: ${intersect(configs, (name) => `DiscoveredConfigEntry<${name}>`)} }
}
`;
}

/** The published plugin factory: the same normalizers apps use, with static imports only. */
function entry(id, module, manifest, local) {
  const imports = [];
  let serial = 0;
  const load = (file) => {
    const name = `entry${serial++}`;
    imports.push(`import ${name} from ${quote(local(file))};`);
    return name;
  };
  const discovered = (entries) =>
    entries.map((item) => {
      const name = load(item.file);
      return `discoveredFile(${name}, ${quote(item.path)}, ${quote(path.relative(module.directory, item.file).split(path.sep).join('/'))})`;
    });
  const metadata = {};
  for (const key of ['name', 'version', 'description', 'author', 'homepage', 'bugs', 'license'])
    if (manifest[key] !== undefined) metadata[key] = manifest[key];
  const services = discovered(module.services);
  const actions = discovered(module.actions);
  const configs = discovered(module.configs);
  const interceptors = discovered(module.interceptors);
  const pages = module.pages.map((item) => load(item.file));
  const views = module.views.map((item) => load(item.file));
  const setup = module.setup ? load(module.setup) : 'undefined';
  return `'use client';
${header}import { definePlugin, discoveredFile, discoverActions, discoverServices, discoverConfig, discoverInterceptors } from '@bitakit/core';
${imports.join('\n')}

/** Creates the ${quote(id)} plugin; apps call this once per provider instance. */
export default function plugin() {
  return definePlugin({
    id: ${quote(id)},
    metadata: ${quote(metadata)},
    dependencies: ${quote(manifest.foundation?.dependencies ?? [])},
    services: discoverServices([${services.join(', ')}], ${quote(id)}),
    actions: discoverActions([${actions.join(', ')}], ${quote(id)}, true),
    config: discoverConfig([${configs.join(', ')}]),
    interceptors: discoverInterceptors([${interceptors.join(', ')}]),
    pages: [${pages.join(', ')}],
    views: [${views.join(', ')}],
    setup: ${setup},
  });
}
`;
}
