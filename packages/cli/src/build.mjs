import { execFileSync } from 'node:child_process';
import { cp, mkdir, realpath, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { describeModule, describeDefinitions, validatePackageStyles } from '@bitakit/discovery';
import { packageMetadataSources, projectPluginMetadata } from '@bitakit/core';
import { findProject } from './project.mjs';

const quote = JSON.stringify;
const header = '// Generated by BitaKit. Do not edit.\n';

/**
 * Builds a plugin package from the same folders apps use. It generates the plugin's own types
 * (`.bitakit/plugin.d.ts`), compiles `src` with the package's TypeScript config and writes
 * `dist/plugin.js`, the entry apps discover. `check` stops after a type check.
 */
export async function buildPlugin({ cwd, check = false } = {}) {
  const project = await findProject(cwd);
  if (project.kind !== 'plugin')
    throw new Error(
      'Run "bitakit build" inside a plugin package (a package.json with a bitakit.plugin entry).',
    );
  const { root, pluginId: id, moduleRoot, manifest, metadata } = project;
  const module = await describeModule(moduleRoot);
  for (const warning of module.warnings) console.warn(`[bitakit] ${warning}`);
  // Discovery resolves symlinks (macOS /var → /private/var); relate the files to the real root,
  // or the generated imports would leave the package and the type augmentation would not apply.
  const realRoot = await realpath(root);
  await mkdir(path.join(root, '.bitakit'), { recursive: true });
  await writeFile(
    path.join(root, '.bitakit/plugin.d.ts'),
    declarations(
      id,
      module,
      (file) =>
        `../${path
          .relative(realRoot, file)
          .split(path.sep)
          .join('/')
          .replace(/\.tsx?$/, '')}`,
    ),
  );
  const tsc = createRequire(path.join(root, 'package.json')).resolve('typescript/bin/tsc');
  const compile = (args) => {
    try {
      execFileSync(process.execPath, [tsc, '-p', 'tsconfig.json', ...args], {
        cwd: root,
        stdio: 'pipe',
      });
    } catch (error) {
      throw new Error(
        `TypeScript found problems:\n${String(error.stdout || error.message).trim()}`,
      );
    }
  };
  if (check) {
    compile(['--noEmit']);
    return { id, module, checked: true };
  }
  const dist = path.join(root, 'dist');
  await rm(dist, { recursive: true, force: true });
  compile([]);
  const local = (file) =>
    `./${path
      .relative(module.directory, file)
      .split(path.sep)
      .join('/')
      .replace(/\.tsx?$/, '.js')}`;
  await writeFile(path.join(dist, 'plugin.js'), entry(id, module, manifest, metadata, local));
  // Derived tooling hints travel with the entry; the source declarations remain the authority.
  const slotInfo = await describeDefinitions(module.slotDefinitions, {
    helper: 'defineSlot',
    moduleId: id,
    properties: ['accepts', 'policy'],
  });
  const source = (file) => path.relative(module.directory, file).split(path.sep).join('/');
  await writeFile(
    path.join(dist, 'plugin.slots.json'),
    JSON.stringify(
      {
        version: 1,
        pluginId: id,
        definitions: slotInfo.definitions.map((item) => ({
          ...item,
          file: source(item.file),
          plugin: id,
          policy: item.policy ?? 'list',
        })),
        unresolved: slotInfo.unresolved.map(source),
      },
      null,
      2,
    ) + '\n',
  );
  await writeFile(
    path.join(dist, 'plugin.d.ts'),
    `${declarations(id, module, (file) => local(file))}import type { Plugin } from '@bitakit/core';
/** Creates the "${id}" plugin. Apps discover it through package.json bitakit.plugin. */
declare const plugin: () => Plugin & { readonly id: ${quote(id)} };
export default plugin;
`,
  );
  if (module.locales.length) {
    await mkdir(path.join(dist, 'locales'), { recursive: true });
    for (const file of module.locales)
      await cp(file, path.join(dist, 'locales', path.basename(file)));
  }
  const styles = (value) =>
    (value === undefined ? [] : Array.isArray(value) ? value : [value]).map(
      (entry) => `${manifest.name}/${entry.replace(/^\.\//, '')}`,
    );
  await validatePackageStyles([
    {
      name: manifest.name,
      manifestFile: path.join(root, 'package.json'),
      manifest,
      styles: styles(metadata.styles),
      theme: styles(metadata.theme),
    },
  ]);
  return { id, module, dist };
}

/** Typed services, actions, events and config for TypeScript, through @bitakit/core augmentation. */
function declarations(id, module, specifier) {
  const lines = [];
  const files = (entries, kind) =>
    entries.map((entry, index) => {
      const name = `${kind}${index}`;
      lines.push(`import type ${name}Entry from ${quote(specifier(entry.file))};`);
      lines.push(`type ${name} = DiscoveredFile<typeof ${name}Entry, ${quote(entry.path)}>;`);
      return name;
    });
  const services = files(module.services, 'Service');
  const settings = files(module.settings, 'Settings');
  const slots = files(module.slotDefinitions, 'Slot');
  const actions = files(module.actions, 'Action');
  const configs = files(module.configs, 'Config');
  const events = files(module.events, 'Events');
  const intersect = (items, map) => items.map(map).join(' & ') || '{}';
  return `${header}import type { DiscoveredFile, DiscoveredSlotEntry, DiscoveredServiceEntry, DiscoveredActionEntry, DiscoveredConfigEntry, DiscoveredEventsEntry, DiscoveredCancelableEntry, DiscoveredSettingsEntry } from '@bitakit/core';
${lines.join('\n')}
type PluginSettings = ${intersect(settings, (name) => `DiscoveredSettingsEntry<${name}, ${quote(id)}>`)};
type PluginSlots = ${intersect(slots, (name) => `DiscoveredSlotEntry<${name}, ${quote(id)}>`)};
type PluginServices = ${intersect(services, (name) => `DiscoveredServiceEntry<${name}, ${quote(id)}>`)};
type PluginActions = ${intersect(actions, (name) => `DiscoveredActionEntry<${name}, ${quote(id)}>`)};
type PluginEvents = ${intersect(events, (name) => `DiscoveredEventsEntry<${name}, ${quote(id)}>`)};
type PluginCancelable = ${intersect(events, (name) => `DiscoveredCancelableEntry<${name}, ${quote(id)}>`)};
declare module '@bitakit/core' {
  interface ServiceMap extends PluginServices {}
  interface ActionMap extends PluginActions {}
  interface EventMap extends PluginEvents {}
  interface CancelableEventMap extends PluginCancelable {}
  interface SlotMap extends PluginSlots {}
  interface SettingsMap extends PluginSettings {}
  interface ConfigMap { ${quote(id)}: ${intersect(configs, (name) => `DiscoveredConfigEntry<${name}>`)} }
}
`;
}

/** The published plugin factory: the same normalizers apps use, with static imports only. */
function entry(id, module, manifest, metadata, local) {
  const imports = [];
  let serial = 0;
  const load = (file, namespace = false) => {
    const name = `${namespace ? 'module' : 'entry'}${serial++}`;
    imports.push(
      namespace
        ? `import * as ${name} from ${quote(local(file))};`
        : `import ${name} from ${quote(local(file))};`,
    );
    return name;
  };
  const discovered = (entries) =>
    entries.map((item) => {
      const name = load(item.file);
      return `discoveredFile(${name}, ${quote(item.path)}, ${quote(path.relative(module.directory, item.file).split(path.sep).join('/'))})`;
    });
  const sources = packageMetadataSources(manifest);
  const { metadata: info, warnings } = projectPluginMetadata(sources.canonical, sources.legacy);
  // Preserve the historical public name fallback; full package identity is recorded separately.
  if (info.name === undefined && typeof manifest.name === 'string') info.name = manifest.name;
  for (const warning of warnings) console.warn(`[bitakit] package.json: ${warning}`);
  const services = discovered(module.services);
  const settings = discovered(module.settings);
  const settingsPage = module.settingsPage
    ? `pluginSettingsPage(${load(module.settingsPage, true)})`
    : undefined;
  const slotDefinitions = discovered(module.slotDefinitions);
  const actions = discovered(module.actions);
  const configs = discovered(module.configs);
  const interceptors = discovered(module.interceptors);
  const events = discovered(module.events);
  const pages = module.pages.map(
    (item) =>
      `pluginPage(${load(item.file, true)}, ${quote(`/${id}${item.path ? `/${item.path.split('.').join('/')}` : ''}`)})`,
  );
  const slots = module.slots.map(
    (item) =>
      `pluginSlot(${load(item.file, true)}, ${quote(item.path)}, ${quote(path.relative(module.directory, item.file).split(path.sep).join('/'))})`,
  );
  const providers = module.providers.map(
    (item) => `pluginProvider(${load(item.file, true)}, ${quote(`${id}.${item.path}`)})`,
  );
  const setup = module.setup ? load(module.setup) : 'undefined';
  return `'use client';
${header}import { definePlugin, discoveredFile, discoverActions, discoverServices, discoverSlots, discoverConfig, discoverInterceptors, discoverEvents, discoverSettings, pluginSettingsPage, pluginPage, pluginSlot, pluginProvider } from '@bitakit/core';
${imports.join('\n')}

/** Creates the ${quote(id)} plugin; apps call this once per runtime. */
export default function plugin() {
  return definePlugin({
    id: ${quote(id)},
    metadata: ${quote(info)},
    dependencies: ${quote(metadata?.dependencies ?? [])},
    events: discoverEvents([${events.join(', ')}]),
    settings: discoverSettings([${settings.join(', ')}]),
    slots: discoverSlots([${slotDefinitions.join(', ')}], ${quote(id)}),
    services: discoverServices([${services.join(', ')}], ${quote(id)}),
    actions: discoverActions([${actions.join(', ')}], ${quote(id)}),
    config: discoverConfig([${configs.join(', ')}]),
    interceptors: discoverInterceptors([${interceptors.join(', ')}]),
    ui: { pages: [${pages.join(', ')}], slots: [${slots.join(', ')}], providers: [${providers.join(', ')}]${settingsPage ? `, settings: ${settingsPage}` : ''} },
    setup: ${setup},
  });
}
`;
}
