test('doctor explains group-only navigation; explicit migration is previewable and idempotent', async (t) => {
  const file = 'src/plugins/notes/actions/open.ts';
  const source =
    "import { defineAction } from '@bitakit/core';\nexport default defineAction({ title: 'Notes', href: '/', groups: ['navigation'] });\n";
  const root = await project(nextApp({ [file]: source }), t);
  const before = await bitakit(root, 'doctor', '--json');
  assert.ok(
    JSON.parse(before.stdout).results.some(
      (item) => item.title === 'Navigation Actions still rely on groups',
    ),
  );
  const preview = await bitakit(
    root,
    'migrate',
    '--navigation-slot',
    'shell.navigation',
    '--dry-run',
  );
  assert.equal(preview.code, 0, preview.stderr);
  assert.match(preview.stdout, /explicitly selected slot/);
  assert.equal(await read(root, file), source);
  const applied = await bitakit(root, 'migrate', '--navigation-slot', 'shell.navigation');
  assert.equal(applied.code, 0, applied.stderr);
  assert.match(await read(root, file), /slots: \["shell.navigation"\]/);
  assert.match(await read(root, file), /groups: \['navigation'\]/);
  const again = await bitakit(root, 'migrate', '--navigation-slot', 'shell.navigation');
  assert.match(again.stdout, /Nothing to migrate/);
  const after = await bitakit(root, 'doctor', '--json');
  assert.ok(
    !JSON.parse(after.stdout).results.some(
      (item) => item.title === 'Navigation Actions still rely on groups',
    ),
  );
});

