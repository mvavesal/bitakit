import test from 'node:test';
import assert from 'node:assert/strict';
import { access, readFile } from 'node:fs/promises';
import path from 'node:path';
import { bitakit, catchAll, link, nextApp, project, write } from './helpers.mjs';

const read = (root, file) => readFile(path.join(root, file), 'utf8');
const exists = (root, file) => access(path.join(root, file));
const missing = (root, file) => assert.rejects(access(path.join(root, file)));

/** A 0.1 app: foundation.config.ts, suffixed files, pages/ folders, .foundation output and Webpack scripts. */
const legacyApp = () => {
  const { 'node_modules/@bitakit/core/package.json': _stub, ...files } = nextApp();
  return {
    ...files,
    'package.json': {
      name: 'legacy',
      dependencies: { next: '16.0.0', '@bitakit/core': '^0.2.0' },
      scripts: { dev: 'foundation-generate && next dev --webpack', build: 'next build --webpack' },
    },
    'foundation.config.ts':
      "import { defineFoundation } from '@bitakit/next/config';\n\nexport default defineFoundation({ groups: ['navigation'] });\n",
    'src/app/layout.tsx':
      "import { FoundationProvider } from '@/.foundation/plugins';\nexport default function Layout({ children }) { return <FoundationProvider>{children}</FoundationProvider>; }\n",
    'src/app/globals.css': "@import 'tailwindcss';\n@import '../../.foundation/styles.css';\n",
    ...catchAll,
    'src/plugins/todos/actions/add.action.ts':
      "import { defineAction } from '@bitakit/core';\nexport default defineAction({ title: 'Add', execute: () => {} });\n",
    'src/plugins/todos/actions/open.ts':
      "import { defineURLAction } from '@bitakit/core';\nexport default defineURLAction({ title: 'Todos', href: '/todos', groups: ['navigation'] });\n",
    'src/plugins/todos/services/todos.service.ts':
      "import { defineService } from '@bitakit/core';\nexport default defineService(() => ({}));\n",
    'src/plugins/todos/pages/todos.tsx':
      "import { definePage } from '@bitakit/core';\nexport default definePage({ path: '/todos', component: () => null });\n",
    '.foundation/plugins.ts': '// Generated by BitaKit. Do not edit.\nexport {};\n',
    'foundation-env.d.ts': '// Generated by BitaKit. Do not edit.\n',
    '.gitignore': 'node_modules/\n.foundation/\nfoundation-env.d.ts\n',
  };
};

test('migrate --dry-run only lists the changes; migrate applies them once and the result passes doctor', async (t) => {
  const root = await project(legacyApp(), t);
  // The rewritten bitakit.config.ts imports @bitakit/core/discovery, so the real package must resolve.
  await link(root, '@bitakit/core', 'packages/core');

  const dry = await bitakit(root, 'migrate', '--dry-run');
  assert.equal(dry.code, 0, dry.stderr);
  assert.match(dry.stdout, /Would change:/);
  assert.match(
    dry.stdout,
    /rename\s+foundation\.config\.ts → bitakit\.config\.ts\s+\(defineFoundation → defineBitaKit\)/,
  );
  assert.match(dry.stdout, /move\s+src\/plugins\/todos\/pages → src\/plugins\/todos\/ui\/pages/);
  assert.match(
    dry.stdout,
    /rename\s+src\/plugins\/todos\/actions\/add\.action\.ts → src\/plugins\/todos\/actions\/add\.ts/,
  );
  assert.match(
    dry.stdout,
    /rename\s+src\/plugins\/todos\/services\/todos\.service\.ts → src\/plugins\/todos\/services\/todos\.ts/,
  );
  assert.match(dry.stdout, /rewrite\s+src\/app\/globals\.css/);
  assert.match(dry.stdout, /rewrite\s+\.gitignore/);
  assert.match(dry.stdout, /delete\s+\.foundation/);
  assert.match(dry.stdout, /Run without --dry-run to apply\./);
  await exists(root, 'foundation.config.ts');
  await exists(root, 'src/plugins/todos/actions/add.action.ts');
  await exists(root, 'src/plugins/todos/pages/todos.tsx');

  const run = await bitakit(root, 'migrate');
  assert.equal(run.code, 0, run.stderr);
  assert.match(run.stdout, /Changed:/);
  assert.match(run.stdout, /Review the diff, then run "bitakit generate" and "bitakit doctor"\./);
  await missing(root, 'foundation.config.ts');
  assert.equal(
    await read(root, 'bitakit.config.ts'),
    "import { defineBitaKit } from '@bitakit/core/discovery';\n\nexport default defineBitaKit({ groups: ['navigation'] });\n",
  );
  await missing(root, 'src/plugins/todos/actions/add.action.ts');
  await exists(root, 'src/plugins/todos/actions/add.ts');
  await missing(root, 'src/plugins/todos/services/todos.service.ts');
  await exists(root, 'src/plugins/todos/services/todos.ts');
  await missing(root, 'src/plugins/todos/pages');
  await exists(root, 'src/plugins/todos/ui/pages/todos.tsx');
  assert.equal(
    await read(root, 'src/app/globals.css'),
    "@import 'tailwindcss';\n@import '../bitakit.gen.css';\n",
  );
  assert.match(await read(root, 'src/app/layout.tsx'), /from '\.\.\/bitakit\.gen'/);
  assert.match(
    await read(root, 'src/plugins/todos/actions/open.ts'),
    /^import \{ defineAction \} from '@bitakit\/core';\nexport default defineAction\(\{ title: 'Todos'/,
  );
  const ignore = await read(root, '.gitignore');
  assert.match(ignore, /src\/bitakit\.gen\.\*/);
  assert.doesNotMatch(ignore, /\.foundation|foundation-env/);
  const manifest = JSON.parse(await read(root, 'package.json'));
  assert.equal(manifest.scripts.dev, 'bitakit generate && next dev');
  assert.equal(manifest.scripts.build, 'next build');
  await missing(root, '.foundation');
  await missing(root, 'foundation-env.d.ts');

  const again = await bitakit(root, 'migrate');
  assert.equal(again.code, 0, again.stderr);
  assert.match(again.stdout, /Nothing to migrate\./);

  const check = await bitakit(root, 'doctor', '--json');
  assert.equal(check.code, 0, check.stdout + check.stderr);
  const report = JSON.parse(check.stdout);
  assert.equal(report.project, 'legacy');
  assert.deepEqual([report.errors, report.warnings], [0, 0]);

  const generate = await bitakit(root, 'generate');
  assert.equal(generate.code, 0, generate.stderr);
  assert.match(generate.stdout, /Generated src\/bitakit\.gen\.tsx \(next\)\./);
  const generated = await read(root, 'src/bitakit.gen.tsx');
  assert.match(generated, /^\/\/ Generated by BitaKit\. Do not edit\./);
  assert.match(generated, /export function BitaKitProvider/);
  assert.match(generated, /id: "todos"/);
  assert.match(generated, /pluginPage\(module\d+, "\/todos\/todos"\)/);
  await exists(root, 'src/bitakit.gen.css');

  const info = await bitakit(root, 'info', '--json');
  assert.equal(info.code, 0, info.stderr);
  const description = JSON.parse(info.stdout);
  assert.deepEqual(
    description.plugins.map((plugin) => plugin.id),
    ['todos'],
  );
  assert.deepEqual(
    description.plugins[0].actions.map((entry) => entry.path),
    ['add', 'open'],
  );
  assert.deepEqual(description.plugins[0].pages, [
    { path: 'todos', file: 'src/plugins/todos/ui/pages/todos.tsx' },
  ]);
  assert.deepEqual(description.warnings, []);
  const text = await bitakit(root, 'info');
  assert.match(
    text.stdout,
    /Plugin "todos" src\/plugins\/todos\n  services: todos\n  actions: add, open\n  pages: todos/,
  );
});

test('add prints the created files, doctor --json reports counts and the exit code follows the errors', async (t) => {
  const root = await project(nextApp(), t);
  const added = await bitakit(root, 'add', 'plugin', 'notes');
  assert.equal(added.code, 0, added.stderr);
  assert.match(added.stdout, /Created plugin "notes":/);
  assert.match(added.stdout, /\+ src\/plugins\/notes\/services\/items\.ts/);
  assert.match(added.stdout, /\+ src\/plugins\/notes\/ui\/pages\/index\.tsx/);
  assert.match(added.stdout, /"Notes" now appears in the navigation and opens \/notes\./);
  const minimal = await bitakit(root, 'add', 'plugin', 'stats', '--minimal');
  assert.equal(minimal.code, 0, minimal.stderr);
  assert.doesNotMatch(minimal.stdout, /navigation/);
  const action = await bitakit(root, 'add', 'action', 'notes/team/invite');
  assert.equal(action.code, 0, action.stderr);
  assert.match(
    action.stdout,
    /Created action "notes\.team\.invite":\n  \+ src\/plugins\/notes\/actions\/team\/invite\.ts/,
  );
  const page = await bitakit(root, 'add', 'page', 'notes/stats');
  assert.match(
    page.stdout,
    /Created page \/notes\/stats:\n  \+ src\/plugins\/notes\/ui\/pages\/stats\.tsx/,
  );
  const events = await bitakit(root, 'add', 'events', 'notes');
  assert.equal(events.code, 1);
  assert.match(events.stderr, /events\.ts already exists/);
  const unnamed = await bitakit(root, 'add', 'events');
  assert.equal(unnamed.code, 1);
  assert.match(unnamed.stderr, /Name the plugin too/);

  const failing = await bitakit(root, 'doctor', '--json');
  assert.equal(failing.code, 1);
  const report = JSON.parse(failing.stdout);
  assert.equal(report.project, 'demo');
  assert.deepEqual([report.errors, report.warnings], [1, 0]);
  assert.deepEqual(
    report.results.filter((result) => result.status !== 'ok').map((result) => result.title),
    ['Some plugin pages cannot be reached'],
  );

  await write(root, catchAll);
  const passing = await bitakit(root, 'doctor');
  assert.equal(passing.code, 0, passing.stdout);
  assert.match(passing.stdout, /BitaKit doctor · demo/);
  assert.match(passing.stdout, /All 2 plugin pages can be reached/);
  assert.match(passing.stdout, /No problems\./);

  const version = await bitakit(root, '--version');
  assert.equal(
    version.stdout.trim(),
    JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8')).version,
  );
});

test('generate and info refuse to run inside a plugin package', async (t) => {
  const root = await project(
    { 'package.json': { name: 'bitakit-widget', bitakit: { plugin: './plugin' } } },
    t,
  );
  for (const command of ['generate', 'info']) {
    const result = await bitakit(root, command);
    assert.equal(result.code, 1);
    assert.match(result.stderr, new RegExp(`Run "bitakit ${command}" inside an app`));
  }
  const build = await bitakit(
    await project({ 'package.json': { name: 'demo', dependencies: { next: '16.0.0' } } }, t),
    'build',
  );
  assert.equal(build.code, 1);
  assert.match(build.stderr, /inside a plugin package/);
});
