import test from 'node:test';
import assert from 'node:assert/strict';
import { access, readFile } from 'node:fs/promises';
import path from 'node:path';
import { buildPlugin, pluginFiles } from '../src/index.mjs';
import { link, project } from './helpers.mjs';

const under = (directory, files) =>
  Object.fromEntries(
    Object.entries(files).map(([file, content]) => [`${directory}/${file}`, content]),
  );
const tsconfig = {
  compilerOptions: {
    target: 'ES2022',
    lib: ['ES2022'],
    module: 'ESNext',
    moduleResolution: 'Bundler',
    strict: true,
    skipLibCheck: true,
    declaration: true,
    verbatimModuleSyntax: true,
    rootDir: 'src',
    outDir: 'dist',
  },
  include: ['src', '.bitakit/plugin.d.ts'],
};
/** The compiler and Core resolve from the workspace; the package itself stays a plain fixture. */
async function toolchain(root) {
  await link(root, '@bitakit/core', 'packages/core');
  await link(root, 'typescript', 'node_modules/typescript');
}

test('build writes the plugin types, the compiled sources and the dist/plugin entry', async (t) => {
  const root = await project(
    {
      'package.json': {
        name: '@acme/bitakit-notes',
        tags: ['productivity'],
        coverImage: '/notes.png',
        version: '0.1.0',
        type: 'module',
        exports: {
          './package.json': './package.json',
          './plugin': { types: './dist/plugin.d.ts', default: './dist/plugin.js' },
        },
        bitakit: { plugin: './plugin', id: 'notes', dependencies: ['shell'] },
        peerDependencies: { '@bitakit/core': '^0.2.0' },
      },
      'tsconfig.json': tsconfig,
      ...under('src', pluginFiles('notes', { minimal: true })),
      'src/setup.ts': 'export default () => {};\n',
      'src/locales/en.json': { notes: { add: { title: 'Add note' } } },
    },
    t,
  );
  await toolchain(root);

  const checked = await buildPlugin({ cwd: root, check: true });
  assert.equal(checked.checked, true);
  assert.equal(checked.id, 'notes');
  await assert.rejects(access(path.join(root, 'dist')));
  const types = await readFile(path.join(root, '.bitakit/plugin.d.ts'), 'utf8');
  assert.match(types, /^\/\/ Generated by BitaKit\. Do not edit\./);
  assert.match(
    types,
    /import type Service0Entry from "\.\.\/src\/services\/list";\ntype Service0 = DiscoveredFile<typeof Service0Entry, "list">;/,
  );
  assert.match(types, /import type Events0Entry from "\.\.\/src\/events";/);
  assert.match(types, /type PluginServices = DiscoveredServiceEntry<Service0, "notes">;/);
  assert.match(types, /type PluginActions = DiscoveredActionEntry<Action0, "notes">;/);
  assert.match(types, /type PluginEvents = DiscoveredEventsEntry<Events0, "notes">;/);
  assert.match(
    types,
    /declare module '@bitakit\/core' \{\n  interface ServiceMap extends PluginServices \{\}\n  interface ActionMap extends PluginActions \{\}\n  interface EventMap extends PluginEvents \{\}\n  interface CancelableEventMap extends PluginCancelable \{\}\n  interface SlotMap extends PluginSlots \{\}\n  interface SettingsMap extends PluginSettings \{\}\n  interface ConfigMap \{ "notes": \{\} \}\n\}/,
  );

  const built = await buildPlugin({ cwd: root });
  assert.equal(built.dist, path.join(root, 'dist'));
  assert.deepEqual(
    [
      built.module.services.length,
      built.module.actions.length,
      built.module.events.length,
      built.module.pages.length,
    ],
    [1, 1, 1, 0],
  );
  const entry = await readFile(path.join(root, 'dist/plugin.js'), 'utf8');
  assert.match(entry, /^'use client';\n\/\/ Generated by BitaKit\. Do not edit\./);
  assert.match(
    entry,
    /import \{ definePlugin, discoveredFile, discoverActions, discoverServices, discoverSlots, discoverConfig, discoverInterceptors, discoverEvents, discoverSettings, pluginSettingsPage, pluginPage, pluginSlot, pluginProvider \} from '@bitakit\/core';/,
  );
  assert.match(entry, /import entry\d+ from "\.\/services\/list\.js";/);
  assert.match(
    entry,
    /export default function plugin\(\) \{\n  return definePlugin\(\{\n    id: "notes",/,
  );
  assert.match(
    entry,
    /metadata: \{"version":"0\.1\.0","coverImage":"\/notes\.png","tags":\["productivity"\],"name":"@acme\/bitakit-notes"\},/,
  );
  assert.match(entry, /dependencies: \["shell"\],/);
  assert.match(
    entry,
    /events: discoverEvents\(\[discoveredFile\(entry\d+, "", "events\.ts"\)\]\),/,
  );
  assert.match(
    entry,
    /services: discoverServices\(\[discoveredFile\(entry\d+, "list", "services\/list\.ts"\)\], "notes"\),/,
  );
  assert.match(
    entry,
    /actions: discoverActions\(\[discoveredFile\(entry\d+, "add", "actions\/add\.ts"\)\], "notes"\),/,
  );
  assert.match(
    entry,
    /config: discoverConfig\(\[\]\),\n    interceptors: discoverInterceptors\(\[\]\),/,
  );
  assert.match(entry, /ui: \{ pages: \[\], slots: \[\], providers: \[\] \},/);
  assert.match(entry, /setup: entry\d+,/);
  const declaration = await readFile(path.join(root, 'dist/plugin.d.ts'), 'utf8');
  assert.match(declaration, /import type Service0Entry from "\.\/services\/list\.js";/);
  assert.match(declaration, /interface ServiceMap extends PluginServices \{\}/);
  assert.match(
    declaration,
    /declare const plugin: \(\) => Plugin & \{ readonly id: "notes" \};\nexport default plugin;\n$/,
  );
  for (const file of [
    'services/list.js',
    'services/list.d.ts',
    'actions/add.js',
    'events.js',
    'setup.js',
    'locales/en.json',
  ])
    await access(path.join(root, 'dist', file));
});

test('build needs a plugin package and reports type errors with the file', async (t) => {
  const app = await project(
    { 'package.json': { name: 'demo', dependencies: { next: '16.0.0' } } },
    t,
  );
  await assert.rejects(buildPlugin({ cwd: app }), /Run "bitakit build" inside a plugin package/);

  const root = await project(
    {
      'package.json': {
        name: 'bitakit-broken',
        type: 'module',
        bitakit: { plugin: './plugin' },
        peerDependencies: { '@bitakit/core': '^0.2.0' },
      },
      'tsconfig.json': tsconfig,
      'src/actions/add.ts':
        "import { defineAction } from '@bitakit/core';\nexport default defineAction({ title: 1, execute: () => {} });\n",
    },
    t,
  );
  await toolchain(root);
  await assert.rejects(
    buildPlugin({ cwd: root, check: true }),
    /TypeScript found problems:[\s\S]*src\/actions\/add\.ts/,
  );
  await assert.rejects(access(path.join(root, 'dist')));
});

test('packaged slot definitions retain runtime ownership, payload types and derived Doctor hints', async (t) => {
  const root = await project(
    {
      'package.json': {
        name: '@acme/bitakit-toolbar',
        version: '0.1.0',
        type: 'module',
        exports: {
          './package.json': './package.json',
          './plugin': { types: './dist/plugin.d.ts', default: './dist/plugin.js' },
        },
        bitakit: { plugin: './plugin', id: 'toolbar' },
        peerDependencies: { '@bitakit/core': '^0.2.0' },
      },
      'tsconfig.json': tsconfig,
      'src/slots/header/index.ts': `import { defineSlot } from '@bitakit/core';
      export default { end: defineSlot({ accepts: 'component', payload: { parse: (_value: unknown) => ({ collapsed: true as boolean }) } }) };`,
      'src/ui/slots/toolbar.header.end.ts': `export const id = 'badge'; export const key = 'status'; export const order = 5; export const availability = 'wait'; export default () => null;`,
      'src/check.ts': `import type { SlotPayload } from '@bitakit/core';
      const payload: SlotPayload<'toolbar.header.end'> = { collapsed: true };
      // @ts-expect-error Package author types come from its own slot declaration.
      const bad: SlotPayload<'toolbar.header.end'> = { collapsed: 'yes' }; void [payload, bad];`,
    },
    t,
  );
  await toolchain(root);
  await buildPlugin({ cwd: root });
  const { default: plugin } = await import(path.join(root, 'dist/plugin.js'));
  const { createRuntime } = await import('../../core/dist/core.js');
  const runtime = createRuntime({ plugins: [plugin()] });
  assert.equal(runtime.modules[1].slots[0].id, 'toolbar.header.end');
  runtime.mount();
  await runtime.ready;
  const item = runtime.slots.get('toolbar.header.end').items[0];
  assert.deepEqual(
    [item.id, item.key, item.order, item.plugin],
    ['toolbar:badge', 'status', 5, 'toolbar'],
  );
  assert.equal(typeof item.component, 'function');
  assert.match(
    await readFile(path.join(root, 'dist/plugin.js'), 'utf8'),
    /ui\/slots\/toolbar\.header\.end\.ts/,
  );
  await runtime.stop();
  const info = JSON.parse(await readFile(path.join(root, 'dist/plugin.slots.json'), 'utf8'));
  assert.deepEqual(info, {
    version: 1,
    pluginId: 'toolbar',
    definitions: [
      {
        id: 'toolbar.header.end',
        file: 'slots/header/index.ts',
        accepts: 'component',
        plugin: 'toolbar',
        policy: 'list',
      },
    ],
    unresolved: [],
  });

  const { mkdir, symlink } = await import('node:fs/promises');
  const app = await project(
    {
      'package.json': { name: 'host', dependencies: { '@acme/bitakit-toolbar': '0.1.0' } },
      'tsconfig.json': {
        ...tsconfig,
        compilerOptions: {
          ...tsconfig.compilerOptions,
          rootDir: '.',
          noEmit: true,
          jsx: 'preserve',
        },
        include: ['src'],
      },
      'src/ui/slots/toolbar.header.end.tsx': 'export default () => null;',
      'src/check.ts': `import './bitakit.gen'; import type { SlotMap, SlotPayload } from '@bitakit/core';
      const payload: SlotPayload<'toolbar.header.end'> = { collapsed: false };
      const kind: SlotMap['toolbar.header.end']['accepts'] = 'component';
      // @ts-expect-error Installed package payload remains typed.
      const bad: SlotPayload<'toolbar.header.end'> = { collapsed: 1 }; void [payload, kind, bad];`,
    },
    t,
  );
  await toolchain(app);
  await mkdir(path.join(app, 'node_modules/@acme'), { recursive: true });
  await symlink(root, path.join(app, 'node_modules/@acme/bitakit-toolbar'), 'dir');
  const { generateBitaKit, describeBitaKit } = await import('@bitakit/discovery');
  const description = await describeBitaKit(app);
  assert.ok(description.slotDeclarations.some((item) => item.id === 'toolbar.header.end'));
  await generateBitaKit(app, { quiet: true });
  // Compile the consumer against the installed package declarations, not workspace source aliases.
  const { execFileSync } = await import('node:child_process');
  const { createRequire } = await import('node:module');
  const tsc = createRequire(path.join(app, 'package.json')).resolve('typescript/bin/tsc');
  execFileSync(process.execPath, [tsc, '-p', 'tsconfig.json'], { cwd: app, stdio: 'pipe' });
  const { doctor } = await import('../src/index.mjs');
  const result = await doctor({ cwd: app });
  assert.equal(
    result.results.find((entry) => /Slot files target declared slots/.test(entry.title))?.status,
    'ok',
  );
});

test('packaged settings and custom pages retain their normalizers, access boundary and slot predicates', async (t) => {
  const root = await project(
    {
      'package.json': {
        name: '@acme/bitakit-preferences',
        version: '0.1.0',
        type: 'module',
        bitakit: { plugin: './plugin', id: 'preferences' },
        peerDependencies: { '@bitakit/core': '^0.2.0' },
      },
      'tsconfig.json': {
        ...tsconfig,
        compilerOptions: { ...tsconfig.compilerOptions, jsx: 'preserve' },
      },
      'src/settings.ts': `import { defineSettings, setting } from '@bitakit/core';
      export default defineSettings({ count: setting({ default: 2 }) }, { title: 'Preferences' });`,
      'src/ui/settings/page.tsx': `export default { component: () => null, boundary: () => null,
      pages: [{ id: 'history', title: 'History', component: () => null }] };`,
      'src/ui/slots/owner.after.ts': `export const when = ({ payload }: { payload: { pageId: string } }) => payload.pageId === 'preferences'; export default () => null;`,
    },
    t,
  );
  await toolchain(root);
  // The test uses no JSX; emit ordinary JS while keeping the conventional .tsx author filename.
  const { writeFile } = await import('node:fs/promises');
  await writeFile(
    path.join(root, 'tsconfig.json'),
    JSON.stringify({ ...tsconfig, compilerOptions: { ...tsconfig.compilerOptions, jsx: 'react' } }),
  );
  const result = await buildPlugin({ cwd: root });
  const plugin = (await import(path.join(result.dist, 'plugin.js'))).default();
  assert.equal(plugin.settings.settings.count.default, 2);
  assert.equal(typeof plugin.ui.settings.boundary, 'function');
  assert.equal(plugin.ui.settings.pages[0].id, 'history');
  assert.equal(plugin.ui.slots[0].when({ payload: { pageId: 'preferences' } }), true);
  assert.equal(plugin.ui.slots[0].when({ payload: { pageId: 'elsewhere' } }), false);
});

test('a numeric-leading historical build ID remains discoverable and metadata.name stays compatible', async (t) => {
  const root = await project(
    {
      'package.json': {
        name: '@acme/2fa',
        version: '1.0.0',
        type: 'module',
        exports: { './package.json': './package.json', './plugin': './dist/plugin.js' },
        bitakit: { plugin: './plugin' },
      },
      'tsconfig.json': tsconfig,
      'src/setup.ts': 'export default () => {};',
    },
    t,
  );
  await toolchain(root);
  const built = await buildPlugin({ cwd: root });
  assert.equal(built.id, '2fa');
  const plugin = (await import(path.join(root, 'dist/plugin.js'))).default();
  assert.equal(plugin.metadata.name, '@acme/2fa');
  const app = await project(
    {
      'package.json': { name: 'host', dependencies: { '@acme/2fa': '1' } },
      'src/plugin.config.ts': 'export default {};',
    },
    t,
  );
  const { mkdir, symlink } = await import('node:fs/promises');
  await mkdir(path.join(app, 'node_modules/@acme'), { recursive: true });
  await symlink(root, path.join(app, 'node_modules/@acme/2fa'), 'dir');
  const { describeBitaKit, generateBitaKit } = await import('@bitakit/discovery');
  const description = await describeBitaKit(app, { packageMetadataOnly: true });
  assert.equal(description.packagePlugins['@acme/2fa/plugin'].pluginId, '2fa');
  await generateBitaKit(app, { quiet: true });
  const { resolveBitaKitConfig } = await import('@bitakit/core');
  assert.doesNotThrow(() => resolveBitaKitConfig({ plugins: [plugin] }));
});
