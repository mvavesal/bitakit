const esc = (value) =>
  String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

function text(x, y, value, o = {}) {
  const attrs = [
    `x="${x}"`,
    `y="${y}"`,
    `font-family="${o.mono ? MONO : SANS}"`,
    `font-size="${o.size ?? 13}"`,
    o.weight ? `font-weight="${o.weight}"` : '',
    `fill="${o.fill}"`,
    o.anchor ? `text-anchor="${o.anchor}"` : '',
    o.spacing ? `letter-spacing="${o.spacing}"` : '',
  ];
  return `<text ${attrs.filter(Boolean).join(' ')}>${esc(value)}</text>`;
}

function rect(x, y, w, h, o = {}) {
  const attrs = [
    `x="${x}"`,
    `y="${y}"`,
    `width="${w}"`,
    `height="${h}"`,
    `rx="${o.rx ?? 8}"`,
    `fill="${o.fill ?? 'none'}"`,
    o.stroke ? `stroke="${o.stroke}" stroke-width="${o.sw ?? 1}"` : '',
    o.dash ? `stroke-dasharray="${o.dash}"` : '',
  ];
  return `<rect ${attrs.filter(Boolean).join(' ')}/>`;
}

function path(points, color, marker) {
  const d = points.map(([x, y], i) => `${i ? 'L' : 'M'}${x} ${y}`).join(' ');
  return `<path d="${d}" fill="none" stroke="${color}" stroke-width="1.5" stroke-linejoin="round" marker-end="url(#${marker})"/>`;
}

function markers(t) {
  const head = (id, color) =>
    `<marker id="${id}" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0 0 L10 5 L0 10 z" fill="${color}"/></marker>`;
  return `<defs>${head('arrow', t.line)}${head('arrow-accent', t.accent)}</defs>`;
}

function svg(w, h, label, body) {
  return `<!-- Generated by scripts/readme-diagrams.mjs. Edit the script and regenerate; do not edit this file. -->\n<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" role="img" aria-label="${esc(label)}"><title>${esc(label)}</title>${body}</svg>\n`;
}

// A plugin drawn as a two-stud building block.
function brick(t, kind, x, y, w, h, name, sub) {
  const c = t[kind];
  const studW = 16;
  const studs = [x + w / 4 - studW / 2, x + (3 * w) / 4 - studW / 2]
    .map((sx) => rect(sx, y - 6, studW, 7, { rx: 2, fill: c.stud }))
    .join('');
  return [
    studs,
    rect(x, y, w, h, { rx: 6, fill: c.fill, stroke: c.stroke, sw: 1.25 }),
    text(x + w / 2, y + 25, name, { size: 13, weight: 600, fill: c.title, anchor: 'middle' }),
    text(x + w / 2, y + 42, sub, { size: 11, fill: c.sub, anchor: 'middle' }),
  ].join('');
}

function architecture(t) {
  const W = 880;
  const H = 472;
  const axis = 343; // Shared vertical axis between the two plugin groups.
  const parts = [markers(t)];

  parts.push(rect(0.5, 0.5, W - 1, H - 1, { rx: 14, fill: t.card, stroke: t.cardStroke }));
  parts.push(rect(20, 20, 840, H - 40, { rx: 12, fill: t.frame, stroke: t.boxStroke }));
  parts.push(text(40, 47, 'Your application', { size: 13, weight: 600, fill: t.text }));
  parts.push(text(840, 47, 'Next.js · TanStack Start', { size: 12, fill: t.muted, anchor: 'end' }));

  // Framework-owned surface.
  parts.push(rect(40, 64, 800, 56, { rx: 10, fill: t.box, stroke: t.boxStroke }));
  parts.push(
    text(440, 88, 'Your pages & components', {
      size: 14,
      weight: 600,
      fill: t.text,
      anchor: 'middle',
    }),
  );
  parts.push(
    text(440, 107, 'routes and rendering stay with your framework', {
      size: 12,
      fill: t.muted,
      anchor: 'middle',
    }),
  );

  // UI binds to the shared action list in Core, between the plugin groups.
  parts.push(
    path(
      [
        [axis, 120],
        [axis, 251],
      ],
      t.line,
      'arrow',
    ),
  );
  parts.push(text(axis + 10, 150, 'binds via @bitakit/ui', { size: 12, fill: t.muted }));

  // Plugin groups.
  parts.push(
    text(40, 180, 'YOUR PLUGINS', { size: 10.5, weight: 600, fill: t.accent, spacing: '0.08em' }),
  );
  parts.push(
    text(365, 180, 'OPTIONAL BITAKIT PLUGINS', {
      size: 10.5,
      weight: 600,
      fill: t.muted,
      spacing: '0.08em',
    }),
  );
  const top = 198;
  const bh = 54;
  const bw = 87;
  const yours = [
    ['todos', 'tasks'],
    ['billing', 'invoices'],
    ['reports', 'analytics'],
  ];
  const kit = [
    ['shell', 'app layout'],
    ['preferences', 'Settings UI'],
    ['search', '⌘K palette'],
    ['auth', 'Better Auth'],
    ['i18n', 'next-intl'],
  ];
  yours.forEach(([name, sub], i) =>
    parts.push(brick(t, 'yours', 40 + i * (bw + 10), top, bw, bh, name, sub)),
  );
  kit.forEach(([name, sub], i) =>
    parts.push(brick(t, 'kit', 365 + i * (bw + 10), top, bw, bh, name, sub)),
  );

  // Core: the plate every plugin snaps onto, with the runtime pieces it owns.
  const coreY = top + bh;
  const coreH = 88;
  parts.push(rect(40, coreY, 800, coreH, { rx: 8, fill: t.core.fill, stroke: t.core.stroke }));
  parts.push(text(60, coreY + 28, 'BitaKit Core', { size: 15, weight: 700, fill: t.core.title }));
  parts.push(
    text(820, coreY + 28, 'starts plugins · checks dependencies · cleans up', {
      size: 12,
      fill: t.core.sub,
      anchor: 'end',
    }),
  );
  const owned = ['services', 'actions', 'events', 'settings', 'slots', 'configs', 'overrides', 'interceptors'];
  const pillGap = 10;
  const pillW = (760 - pillGap * (owned.length - 1)) / owned.length;
  owned.forEach((label, i) => {
    const px = 60 + i * (pillW + pillGap);
    parts.push(rect(px, coreY + 44, pillW, 28, { rx: 14, fill: t.core.pill }));
    parts.push(
      text(px + pillW / 2, coreY + 62, label, {
        size: 12,
        weight: 500,
        fill: t.core.pillText,
        anchor: 'middle',
      }),
    );
  });

  // Build-time adapter feeding Core.
  const adapterY = coreY + coreH + 36;
  parts.push(
    path(
      [
        [axis, adapterY],
        [axis, coreY + coreH + 1],
      ],
      t.line,
      'arrow',
    ),
  );
  parts.push(
    text(axis + 10, adapterY - 13, 'generates registration & types', { size: 12, fill: t.muted }),
  );
  parts.push(rect(40, adapterY, 800, 52, { rx: 10, fill: t.box, stroke: t.boxStroke }));
  parts.push(
    text(60, adapterY + 22, 'BitaKit discovery + framework adapter', { size: 13, weight: 600, fill: t.text }),
  );
  parts.push(
    text(60, adapterY + 40, 'imports + types at build time · no browser file scanning', {
      size: 12,
      fill: t.muted,
    }),
  );

  return svg(
    W,
    H,
    'BitaKit architecture: your pages use @bitakit/ui to bind actions in headless Core; your plugins and optional BitaKit plugins share Core services, actions, events, settings, slots, configs, overrides and interceptors; discovery and the framework adapter generate imports and types at build time.',
    parts.join(''),
  );
}

function step(t, x, y, n, label, accent) {
  const color = accent ? t.accent : t.line;
  const width = 18 + 6 + label.length * 6.6;
  const start = x - width / 2;
  return [
    `<circle cx="${start + 9}" cy="${y - 4}" r="9" fill="${color}"/>`,
    text(start + 9, y, String(n), {
      size: 11,
      weight: 700,
      fill: accent ? t.onAccent : t.frame,
      anchor: 'middle',
    }),
    text(start + 24, y, label, { size: 12, fill: accent ? t.accent : t.muted }),
  ].join('');
}

function actionLoop(t) {
  const W = 880;
  const H = 272;
  const y0 = 52;
  const bh = 140;
  const bw = 142;
  const gap = 88;
  const xs = [24, 24 + bw + gap, 24 + 2 * (bw + gap), 24 + 3 * (bw + gap)];
  const parts = [markers(t)];

  parts.push(rect(0.5, 0.5, W - 1, H - 1, { rx: 14, fill: t.card, stroke: t.cardStroke }));

  const box = (x, kind, accent) => {
    parts.push(
      rect(x, y0, bw, bh, {
        rx: 10,
        fill: t.frame,
        stroke: accent ? t.accent : t.boxStroke,
        sw: accent ? 1.5 : 1,
      }),
    );
    parts.push(
      text(x + 16, y0 + 24, kind, {
        size: 10.5,
        weight: 600,
        fill: accent ? t.accent : t.muted,
        spacing: '0.08em',
      }),
    );
  };

  // 1. Bound controls.
  box(xs[0], 'YOUR UI');
  ['Button', 'Menu item', 'Shortcut'].forEach((label, i) => {
    const py = y0 + 36 + i * 32;
    parts.push(rect(xs[0] + 16, py, bw - 32, 26, { rx: 13, fill: t.box, stroke: t.boxStroke }));
    parts.push(text(xs[0] + bw / 2, py + 17, label, { size: 12, fill: t.text, anchor: 'middle' }));
  });

  // 2. The action and its shared state.
  box(xs[1], 'ACTION', true);
  parts.push(
    text(xs[1] + 16, y0 + 52, 'todos.delete', { size: 13, weight: 600, fill: t.text, mono: true }),
  );
  const tx = xs[1] + 16;
  const ty = y0 + 72;
  parts.push(rect(tx, ty, 30, 16, { rx: 8, fill: t.accentSoft }));
  parts.push(`<circle cx="${tx + 22}" cy="${ty + 8}" r="6" fill="#ffffff"/>`);
  parts.push(text(tx + 40, ty + 12.5, 'enabled', { size: 12, fill: t.text }));
  parts.push(text(xs[1] + 16, y0 + 118, 'reads the store', { size: 11.5, fill: t.muted }));

  // 3. The service that owns the data.
  box(xs[2], 'SERVICE');
  parts.push(
    text(xs[2] + 16, y0 + 52, 'tasks', { size: 13, weight: 600, fill: t.text, mono: true }),
  );
  parts.push(text(xs[2] + 16, y0 + 76, 'remove()', { size: 11.5, fill: t.muted, mono: true }));
  parts.push(text(xs[2] + 16, y0 + 94, 'list()', { size: 11.5, fill: t.muted, mono: true }));

  // 4. The service's observable store.
  box(xs[3], 'STORE');
  parts.push(
    text(xs[3] + 16, y0 + 52, 'tasks.state', { size: 13, weight: 600, fill: t.text, mono: true }),
  );
  parts.push(text(xs[3] + 16, y0 + 76, 'observable state', { size: 11.5, fill: t.muted }));

  // Forward path.
  const fy = y0 + 52;
  parts.push(
    path(
      [
        [xs[0] + bw, fy],
        [xs[1] - 1, fy],
      ],
      t.line,
      'arrow',
    ),
  );
  parts.push(step(t, xs[0] + bw + gap / 2, fy - 12, 1, 'execute'));
  parts.push(
    path(
      [
        [xs[1] + bw, fy],
        [xs[2] - 1, fy],
      ],
      t.line,
      'arrow',
    ),
  );
  parts.push(step(t, xs[1] + bw + gap / 2, fy - 12, 2, 'remove()'));
  parts.push(
    path(
      [
        [xs[2] + bw, fy],
        [xs[3] - 1, fy],
      ],
      t.line,
      'arrow',
    ),
  );
  parts.push(step(t, xs[2] + bw + gap / 2, fy - 12, 3, 'state.set()'));

  // Return path: the store change re-evaluates enabled, and the new state reaches every control.
  const by = y0 + bh;
  const loopY = by + 30;
  const actionX = xs[1] + bw / 2;
  const eventX = xs[3] + bw / 2;
  parts.push(
    path(
      [
        [eventX, by],
        [eventX, loopY],
        [actionX, loopY],
        [actionX, by + 1],
      ],
      t.accent,
      'arrow-accent',
    ),
  );
  parts.push(step(t, (actionX + eventX) / 2, loopY + 22, 4, 'enabled re-evaluated', true));
  const ry = y0 + 112;
  parts.push(
    path(
      [
        [xs[1], ry],
        [xs[0] + bw + 1, ry],
      ],
      t.accent,
      'arrow-accent',
    ),
  );
  parts.push(step(t, xs[0] + bw + gap / 2, ry - 12, 5, 'new state', true));

  return svg(
    W,
    H,
    'Action loop: a bound button, menu item or shortcut executes todos.delete; the action calls tasks.remove(); the service updates its store; the store change re-evaluates the action enabled function; every bound control receives the new state.',
    parts.join(''),
  );
}

for (const [name, theme] of Object.entries(themes)) {
  writeFileSync(join(outDir, `architecture-${name}.svg`), architecture(theme));
  writeFileSync(join(outDir, `action-loop-${name}.svg`), actionLoop(theme));
}
